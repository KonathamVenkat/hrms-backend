   SET i.PERCENTAGE = 3.33, i.UPDATED_AT = SYSTIMESTAMP
 WHERE i.PERCENTAGE = 3.3333333333
   AND i.COMPONENT_ID = (SELECT c.COMPONENT_ID FROM HRMS.SALARY_COMPONENTS c WHERE c.COMPONENT_CODE = 'ARMED_FORCES');
UPDATE HRMS.SALARY_COMPONENTS
   SET DEFAULT_VALUE = 3.33, UPDATED_AT = SYSTIMESTAMP
 WHERE COMPONENT_CODE = 'ARMED_FORCES' AND DEFAULT_VALUE = 3.3333333333;
