-- UNDO of db/masters_menu_reference.sql: removes the 16 sidebar entries and their rights, and the Personal Masters
-- menu, and puts Time and Leave and Admin Config back at 17 and 18.
-- Run as the HRMS user.

DELETE FROM HRMS.ROLE_RIGHTS
 WHERE MENU_ID IN (SELECT SUB_MENU_ID FROM HRMS.SUB_MENU
                    WHERE SUB_MENU_CODE IN ('ADMIN_REGIONS', 'ADMIN_WILAYAS', 'ADMIN_PROVINCES', 'ADMIN_CITIES',
                           'ADMIN_DIRECTORATES', 'ADMIN_GRADES', 'ADMIN_CONTRACT_TYPES', 'ADMIN_PROFESSIONS',
                           'ADMIN_EDUCATION_LEVELS', 'ADMIN_NATIONALITIES', 'ADMIN_RELIGIONS', 'ADMIN_LANGUAGES',
                           'ADMIN_LANGUAGE_LEVELS', 'ADMIN_HOUSE_TYPES', 'ADMIN_RELATION_TYPES', 'ADMIN_RELATIONS'));

DELETE FROM HRMS.SUB_MENU
 WHERE SUB_MENU_CODE IN ('ADMIN_REGIONS', 'ADMIN_WILAYAS', 'ADMIN_PROVINCES', 'ADMIN_CITIES',
                         'ADMIN_DIRECTORATES', 'ADMIN_GRADES', 'ADMIN_CONTRACT_TYPES', 'ADMIN_PROFESSIONS',
                         'ADMIN_EDUCATION_LEVELS', 'ADMIN_NATIONALITIES', 'ADMIN_RELIGIONS', 'ADMIN_LANGUAGES',
                         'ADMIN_LANGUAGE_LEVELS', 'ADMIN_HOUSE_TYPES', 'ADMIN_RELATION_TYPES', 'ADMIN_RELATIONS');

DELETE FROM HRMS.MAIN_MENU WHERE MAIN_MENU_NAME = 'Personal Masters';

UPDATE HRMS.MAIN_MENU SET SORT_ORDER = 17 WHERE MAIN_MENU_NAME = 'Time and Leave';
UPDATE HRMS.MAIN_MENU SET SORT_ORDER = 18 WHERE MAIN_MENU_NAME = 'Admin Config';

COMMIT;
