-- ROLLBACK of db/organisation_menu.sql: removes the Organisation menu entries and their role rights.
-- Run as the HRMS user, by hand. Children go before parents.

DELETE FROM HRMS.ROLE_RIGHTS
 WHERE MENU_ID IN (SELECT SUB_MENU_ID FROM HRMS.SUB_MENU WHERE SUB_MENU_CODE IN ('ORG_BRANCH_SETUP', 'ORG_BRANCH_ASSIGNMENTS'));
DELETE FROM HRMS.SUB_MENU WHERE SUB_MENU_CODE IN ('ORG_BRANCH_SETUP', 'ORG_BRANCH_ASSIGNMENTS');
DELETE FROM HRMS.MAIN_MENU WHERE MAIN_MENU_NAME = 'Organisation'
   AND NOT EXISTS (SELECT 1 FROM HRMS.SUB_MENU s WHERE s.MAIN_MENU_ID = HRMS.MAIN_MENU.MAIN_MENU_ID);
COMMIT;
