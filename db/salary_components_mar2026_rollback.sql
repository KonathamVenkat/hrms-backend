-- Undo db/salary_components_mar2026.sql: removes the 30 components it added.
-- Refuses to run while any of them is used in a salary structure (deleting would break that structure).
-- Also puts HRA back to 25% (the script set it to 20%).
-- Run as the HRMS user. Ends with COMMIT. The other step 2 updates were left commented, so there is nothing else to undo.
DECLARE
  used NUMBER;
BEGIN
  SELECT COUNT(*) INTO used
    FROM HRMS.SALARY_STRUCTURE_ITEMS i JOIN HRMS.SALARY_COMPONENTS c ON c.COMPONENT_ID = i.COMPONENT_ID
   WHERE c.COMPONENT_CODE IN ('COLA', 'NATURE_OF_WORK', 'ADMIN_ALLOW', 'QUALIFICATION', 'SOCIAL_ALLOW', 'PETROL', 'TRANSFER_ALLOW', 'INSURANCE', 'INCOME_TAX', 'ZAKAT', 'ARMED_FORCES', 'ADV_EMERGENCY', 'ADV_EMERGENCY_2', 'ADV_CAR', 'ADV_CAR_2', 'ADV_MOTORCYCLE', 'ADV_BUILDING_1', 'ADV_BUILDING_2', 'HOUSE_MORTGAGE', 'ADV_MEDIUM_TERM', 'ADV_MARRIAGE', 'ADV_HOME_MAINT', 'ADV_CAR_MAINT', 'ADV_HOME_IMPROVE', 'LAND_PURCHASE', 'ADV_HOME_MAINT_MAJOR', 'ADV_CAR_INSURANCE', 'PENALTY', 'ADV_LONG_TERM', 'MINISTER_DED');
  IF used > 0 THEN
    RAISE_APPLICATION_ERROR(-20001, used || ' salary structure item(s) use these components: remove them from the structures first.');
  END IF;
  DELETE FROM HRMS.SALARY_COMPONENTS WHERE COMPONENT_CODE IN ('COLA', 'NATURE_OF_WORK', 'ADMIN_ALLOW', 'QUALIFICATION', 'SOCIAL_ALLOW', 'PETROL', 'TRANSFER_ALLOW', 'INSURANCE', 'INCOME_TAX', 'ZAKAT', 'ARMED_FORCES', 'ADV_EMERGENCY', 'ADV_EMERGENCY_2', 'ADV_CAR', 'ADV_CAR_2', 'ADV_MOTORCYCLE', 'ADV_BUILDING_1', 'ADV_BUILDING_2', 'HOUSE_MORTGAGE', 'ADV_MEDIUM_TERM', 'ADV_MARRIAGE', 'ADV_HOME_MAINT', 'ADV_CAR_MAINT', 'ADV_HOME_IMPROVE', 'LAND_PURCHASE', 'ADV_HOME_MAINT_MAJOR', 'ADV_CAR_INSURANCE', 'PENALTY', 'ADV_LONG_TERM', 'MINISTER_DED');
  DBMS_OUTPUT.PUT_LINE(SQL%ROWCOUNT || ' component(s) removed');
  UPDATE HRMS.SALARY_COMPONENTS SET DEFAULT_VALUE = 25, VERSION = VERSION + 1, UPDATED_AT = SYSTIMESTAMP, UPDATED_BY = 'SYSTEM'
   WHERE COMPONENT_CODE = 'HRA' AND DEFAULT_VALUE = 20;
  DBMS_OUTPUT.PUT_LINE(SQL%ROWCOUNT || ' HRA row(s) set back to 25%');
END;
/
COMMIT;
