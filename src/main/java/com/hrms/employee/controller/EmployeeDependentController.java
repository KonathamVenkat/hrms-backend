package com.hrms.employee.controller;

import com.hrms.auth.security.EmployeeAccessGuard;
import com.hrms.common.dto.ApiResponse;
import com.hrms.employee.dto.request.EmployeeDependentRequest;
import com.hrms.employee.dto.response.EmployeeDependentResponse;
import com.hrms.employee.service.EmployeeDependentService;
import jakarta.validation.Valid;
import lombok.RequiredArgsConstructor;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.web.bind.annotation.*;

import java.util.List;

/**
 * Dependants of one employee. Read: HR staff, or the employee for their own record. Write: HR_ADMIN only.
 * A record is deactivated, never deleted. Generated by tools/generate_employee_info.py.
 */
@RestController
@RequestMapping("/api/v1/employees/{employeeId}/dependants")
@RequiredArgsConstructor
public class EmployeeDependentController {

    private final EmployeeDependentService service;
    private final EmployeeAccessGuard accessGuard;

    @GetMapping
    @PreAuthorize("isAuthenticated()")
    public ResponseEntity<ApiResponse<List<EmployeeDependentResponse>>> getAll(@PathVariable Long employeeId) {
        accessGuard.assertSelfOrPrivileged(employeeId);
        return ResponseEntity.ok(ApiResponse.<List<EmployeeDependentResponse>>builder()
            .success(true).message("Dependants fetched successfully")
            .data(service.getAll(employeeId)).statusCode(200).build());
    }

    @PostMapping
    @PreAuthorize("hasRole('HR_ADMIN')")
    public ResponseEntity<ApiResponse<EmployeeDependentResponse>> add(
            @PathVariable Long employeeId, @Valid @RequestBody EmployeeDependentRequest request) {
        return ResponseEntity.status(HttpStatus.CREATED).body(ApiResponse.<EmployeeDependentResponse>builder()
            .success(true).message("Dependant added successfully")
            .data(service.add(employeeId, request)).statusCode(201).build());
    }

    @PutMapping("/{id}")
    @PreAuthorize("hasRole('HR_ADMIN')")
    public ResponseEntity<ApiResponse<EmployeeDependentResponse>> update(
            @PathVariable Long employeeId, @PathVariable Long id, @Valid @RequestBody EmployeeDependentRequest request) {
        return ResponseEntity.ok(ApiResponse.<EmployeeDependentResponse>builder()
            .success(true).message("Dependant updated successfully")
            .data(service.update(employeeId, id, request)).statusCode(200).build());
    }

    @PatchMapping("/{id}/deactivate")
    @PreAuthorize("hasRole('HR_ADMIN')")
    public ResponseEntity<ApiResponse<Void>> deactivate(@PathVariable Long employeeId, @PathVariable Long id) {
        service.deactivate(employeeId, id);
        return ResponseEntity.ok(ApiResponse.<Void>builder()
            .success(true).message("Dependant deactivated").statusCode(200).build());
    }

    @PatchMapping("/{id}/activate")
    @PreAuthorize("hasRole('HR_ADMIN')")
    public ResponseEntity<ApiResponse<Void>> activate(@PathVariable Long employeeId, @PathVariable Long id) {
        service.activate(employeeId, id);
        return ResponseEntity.ok(ApiResponse.<Void>builder()
            .success(true).message("Dependant activated").statusCode(200).build());
    }
}
