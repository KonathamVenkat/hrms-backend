package com.hrms.employee.service.impl;

import com.hrms.auth.service.AuditTrail;
import com.hrms.common.exception.BadRequestException;
import com.hrms.common.exception.BusinessRuleException;
import com.hrms.common.exception.ResourceNotFoundException;
import com.hrms.common.util.Strings;
import com.hrms.employee.dto.request.EmployeeDependentRequest;
import com.hrms.employee.dto.response.EmployeeDependentResponse;
import com.hrms.employee.entity.EmployeeDependent;
import com.hrms.employee.entity.Relation;
import com.hrms.employee.repository.RelationRepository;
import com.hrms.employee.repository.EmployeeDependentRepository;
import com.hrms.employee.repository.EmployeeRepository;
import com.hrms.employee.service.EmployeeDependentService;
import com.hrms.employee.service.EmployeeChecks;
import jakarta.persistence.EntityManager;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.util.Comparator;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.function.Function;
import java.util.stream.Collectors;
import java.util.stream.Stream;

/**
 * Dependants of an employee. Generated by tools/generate_employee_info.py. Writers are HR_ADMIN only (the controller);
 * the audit trail carries ids and never the personal values.
 */
@Slf4j
@Service
@RequiredArgsConstructor
@Transactional(readOnly = true)
public class EmployeeDependentServiceImpl implements EmployeeDependentService {

    private static final String TARGET = "EMPLOYEE_DEPENDENT";

    private final EmployeeDependentRepository repository;
    private final EmployeeRepository employeeRepository;
    private final RelationRepository relationRepository;
    private final AuditTrail audit;
    private final EntityManager entityManager;

    @Override
    public List<EmployeeDependentResponse> getAll(Long employeeId) {
        EmployeeChecks.requireExists(employeeRepository, employeeId);
        List<EmployeeDependent> rows = repository.findByEmployeeIdOrderByIdAsc(employeeId);
        Refs refs = refsFor(rows);
        return rows.stream()
            .sorted(Comparator.comparing((EmployeeDependent e) -> !e.getIsActive())
                .thenComparing(e -> e.getId()))
            .map(e -> toResponse(e, refs))
            .toList();
    }

    @Override
    @Transactional
    public EmployeeDependentResponse add(Long employeeId, EmployeeDependentRequest request) {
        EmployeeChecks.requireExists(employeeRepository, employeeId);
        validate(request, null);
        EmployeeDependent e = EmployeeDependent.builder().employeeId(employeeId).isActive(true).isAlive(true).build();
        apply(e, request);
        EmployeeDependent saved = repository.save(e);
        entityManager.flush();
        log.info("Dependant {} added for employee {}", saved.getId(), employeeId);
        audit.record("EMPLOYEE_DEPENDENT_ADDED", TARGET, saved.getId(), summary(saved));
        return toResponse(saved, refsFor(List.of(saved)));
    }

    @Override
    @Transactional
    public EmployeeDependentResponse update(Long employeeId, Long id, EmployeeDependentRequest request) {
        EmployeeDependent existing = find(employeeId, id);
        if (request.getVersion() == null) throw new BadRequestException("version is required to update a record");
        Versions.requireCurrent(request.getVersion(), existing.getVersion());
        if (!existing.getIsActive()) {
            throw new BusinessRuleException("RECORD_INACTIVE", "A deactivated record cannot be edited. Activate it first.");
        }
        validate(request, existing);
        apply(existing, request);
        EmployeeDependent saved = repository.save(existing);
        entityManager.flush(); // so the response carries the incremented version
        audit.record("EMPLOYEE_DEPENDENT_UPDATED", TARGET, id, summary(saved));
        return toResponse(saved, refsFor(List.of(saved)));
    }

    @Override
    @Transactional
    public void deactivate(Long employeeId, Long id) {
        EmployeeDependent e = find(employeeId, id);
        if (!e.getIsActive()) return;
        e.setIsActive(false);
        repository.save(e);
        audit.record("EMPLOYEE_DEPENDENT_DEACTIVATED", TARGET, id, summary(e));
    }

    @Override
    @Transactional
    public void activate(Long employeeId, Long id) {
        EmployeeDependent e = find(employeeId, id);
        if (e.getIsActive()) return;
        e.setIsActive(true);
        repository.save(e);
        audit.record("EMPLOYEE_DEPENDENT_ACTIVATED", TARGET, id, summary(e));
    }

    // ── helpers ────────────────────────────────────────────────

    /** The record of THIS employee only: another employee's record is reported as not found. */
    private EmployeeDependent find(Long employeeId, Long id) {
        EmployeeDependent e = repository.findById(id).orElseThrow(() -> new ResourceNotFoundException("Dependant", "id", id));
        if (!e.getEmployeeId().equals(employeeId)) throw new ResourceNotFoundException("Dependant", "id", id);
        return e;
    }

    private void validate(EmployeeDependentRequest r, EmployeeDependent current) {
        requireActive(r.getRelationId() == null ? null : relationRepository.findById(r.getRelationId()).orElse(null), r.getRelationId(), current == null ? null : current.getRelationId(), "RELATION", "Relation");
    }

    private static void apply(EmployeeDependent e, EmployeeDependentRequest r) {
        e.setRelationId(r.getRelationId());
        e.setFirstName(r.getFirstName().trim());
        e.setMiddleName(Strings.trimToNull(r.getMiddleName()));
        e.setLastName(Strings.trimToNull(r.getLastName()));
        e.setFirstNameAr(Strings.trimToNull(r.getFirstNameAr()));
        e.setMiddleNameAr(Strings.trimToNull(r.getMiddleNameAr()));
        e.setLastNameAr(Strings.trimToNull(r.getLastNameAr()));
        e.setGender(r.getGender());
        e.setDateOfBirth(r.getDateOfBirth());
        e.setBirthPlace(Strings.trimToNull(r.getBirthPlace()));
        if (r.getIsAlive() != null) e.setIsAlive(r.getIsAlive());
        e.setPhone(Strings.trimToNull(r.getPhone()));
        e.setAddress(Strings.trimToNull(r.getAddress()));
    }

    private static String summary(EmployeeDependent e) {
        return "employeeId=" + e.getEmployeeId() + ", active=" + e.getIsActive();
    }

    /** A chosen master value must exist and be active; the value the record already holds may stay as it is. */
    private static void requireActive(Object master, Long id, Long currentId, String rule, String label) {
        if (id == null) return;
        if (master == null) throw new ResourceNotFoundException(label, "id", id);
        if (!id.equals(currentId) && !Boolean.TRUE.equals(activeOf(master))) {
            throw new BusinessRuleException(rule + "_INACTIVE", label + " is not active.");
        }
    }

    private static Boolean activeOf(Object master) {
        if (master instanceof Relation m) return m.getIsActive();
        return Boolean.FALSE;
    }

    private record Refs(Map<Long, Relation> relation) {}

    private Refs refsFor(List<EmployeeDependent> rows) {
        return new Refs(
            byId(relationRepository.findAllById(rows.stream().flatMap(e -> Stream.of(e.getRelationId())).filter(Objects::nonNull).collect(Collectors.toSet())), Relation::getId));
    }

    private static <T> Map<Long, T> byId(List<T> rows, Function<T, Long> id) {
        return rows.stream().collect(Collectors.toMap(id, Function.identity()));
    }

    private static String nameOf(Relation m) {
        return m == null ? null : m.getName();
    }

    private static String nameArOf(Relation m) {
        return m == null ? null : m.getNameAr();
    }

    private EmployeeDependentResponse toResponse(EmployeeDependent e, Refs refs) {
        return EmployeeDependentResponse.builder()
            .id(e.getId())
            .employeeId(e.getEmployeeId())
            .relationId(e.getRelationId())
            .relationName(nameOf(refs.relation().get(e.getRelationId())))
            .relationNameAr(nameArOf(refs.relation().get(e.getRelationId())))
            .firstName(e.getFirstName())
            .middleName(e.getMiddleName())
            .lastName(e.getLastName())
            .firstNameAr(e.getFirstNameAr())
            .middleNameAr(e.getMiddleNameAr())
            .lastNameAr(e.getLastNameAr())
            .gender(e.getGender())
            .dateOfBirth(e.getDateOfBirth())
            .birthPlace(e.getBirthPlace())
            .isAlive(e.getIsAlive())
            .phone(e.getPhone())
            .address(e.getAddress())
            .isActive(e.getIsActive())
            .version(e.getVersion())
            .build();
    }
}
