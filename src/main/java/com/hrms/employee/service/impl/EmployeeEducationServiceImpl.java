package com.hrms.employee.service.impl;

import com.hrms.auth.service.AuditTrail;
import com.hrms.common.exception.BadRequestException;
import com.hrms.common.exception.BusinessRuleException;
import com.hrms.common.exception.ResourceNotFoundException;
import com.hrms.common.util.Strings;
import com.hrms.employee.dto.request.EmployeeEducationRequest;
import com.hrms.employee.dto.response.EmployeeEducationResponse;
import com.hrms.employee.entity.EmployeeEducation;
import com.hrms.employee.entity.EducationLevel;
import com.hrms.employee.repository.EducationLevelRepository;
import com.hrms.employee.repository.EmployeeEducationRepository;
import com.hrms.employee.repository.EmployeeRepository;
import com.hrms.employee.service.EmployeeEducationService;
import com.hrms.employee.service.EmployeeChecks;
import jakarta.persistence.EntityManager;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.util.Comparator;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.function.Function;
import java.util.stream.Collectors;
import java.util.stream.Stream;

/**
 * Education records of an employee. Generated by tools/generate_employee_info.py. Writers are HR_ADMIN only (the controller);
 * the audit trail carries ids and never the personal values.
 */
@Slf4j
@Service
@RequiredArgsConstructor
@Transactional(readOnly = true)
public class EmployeeEducationServiceImpl implements EmployeeEducationService {

    private static final String TARGET = "EMPLOYEE_EDUCATION";

    private final EmployeeEducationRepository repository;
    private final EmployeeRepository employeeRepository;
    private final EducationLevelRepository educationLevelRepository;
    private final AuditTrail audit;
    private final EntityManager entityManager;

    @Override
    public List<EmployeeEducationResponse> getAll(Long employeeId) {
        EmployeeChecks.requireExists(employeeRepository, employeeId);
        List<EmployeeEducation> rows = repository.findByEmployeeIdOrderByIdAsc(employeeId);
        Refs refs = refsFor(rows);
        return rows.stream()
            .sorted(Comparator.comparing((EmployeeEducation e) -> !e.getIsActive())
                .thenComparing(Comparator.comparing(EmployeeEducation::getStartDate, Comparator.nullsLast(Comparator.reverseOrder())))
                .thenComparing(EmployeeEducation::getId))
            .map(e -> toResponse(e, refs))
            .toList();
    }

    @Override
    @Transactional
    public EmployeeEducationResponse add(Long employeeId, EmployeeEducationRequest request) {
        EmployeeChecks.requireExists(employeeRepository, employeeId);
        validate(request, null);
        EmployeeEducation e = EmployeeEducation.builder().employeeId(employeeId).isActive(true).build();
        apply(e, request);
        EmployeeEducation saved = repository.save(e);
        entityManager.flush();
        log.info("Education record {} added for employee {}", saved.getId(), employeeId);
        audit.record("EMPLOYEE_EDUCATION_ADDED", TARGET, saved.getId(), summary(saved));
        return toResponse(saved, refsFor(List.of(saved)));
    }

    @Override
    @Transactional
    public EmployeeEducationResponse update(Long employeeId, Long id, EmployeeEducationRequest request) {
        EmployeeEducation existing = find(employeeId, id);
        if (request.getVersion() == null) throw new BadRequestException("version is required to update a record");
        Versions.requireCurrent(request.getVersion(), existing.getVersion());
        if (!existing.getIsActive()) {
            throw new BusinessRuleException("RECORD_INACTIVE", "A deactivated record cannot be edited. Activate it first.");
        }
        validate(request, existing);
        apply(existing, request);
        EmployeeEducation saved = repository.save(existing);
        entityManager.flush(); // so the response carries the incremented version
        audit.record("EMPLOYEE_EDUCATION_UPDATED", TARGET, id, summary(saved));
        return toResponse(saved, refsFor(List.of(saved)));
    }

    @Override
    @Transactional
    public void deactivate(Long employeeId, Long id) {
        EmployeeEducation e = find(employeeId, id);
        if (!e.getIsActive()) return;
        e.setIsActive(false);
        repository.save(e);
        audit.record("EMPLOYEE_EDUCATION_DEACTIVATED", TARGET, id, summary(e));
    }

    @Override
    @Transactional
    public void activate(Long employeeId, Long id) {
        EmployeeEducation e = find(employeeId, id);
        if (e.getIsActive()) return;
        e.setIsActive(true);
        repository.save(e);
        audit.record("EMPLOYEE_EDUCATION_ACTIVATED", TARGET, id, summary(e));
    }

    // ── helpers ────────────────────────────────────────────────

    /** The record of THIS employee only: another employee's record is reported as not found. */
    private EmployeeEducation find(Long employeeId, Long id) {
        EmployeeEducation e = repository.findById(id).orElseThrow(() -> new ResourceNotFoundException("Education record", "id", id));
        if (!e.getEmployeeId().equals(employeeId)) throw new ResourceNotFoundException("Education record", "id", id);
        return e;
    }

    private void validate(EmployeeEducationRequest r, EmployeeEducation current) {
        if (r.getStartDate() != null && r.getEndDate() != null && r.getEndDate().isBefore(r.getStartDate())) {
            throw new BusinessRuleException("INVALID_DATE_RANGE", "The end date cannot be before the start date.");
        }
        requireActive(r.getEducationLevelId() == null ? null : educationLevelRepository.findById(r.getEducationLevelId()).orElse(null), r.getEducationLevelId(), current == null ? null : current.getEducationLevelId(), "EDUCATION_LEVEL", "Education level");
    }

    private static void apply(EmployeeEducation e, EmployeeEducationRequest r) {
        e.setEducationLevelId(r.getEducationLevelId());
        e.setQualification(r.getQualification().trim());
        e.setQualificationAr(Strings.trimToNull(r.getQualificationAr()));
        e.setInstitution(Strings.trimToNull(r.getInstitution()));
        e.setStartDate(r.getStartDate());
        e.setEndDate(r.getEndDate());
    }

    private static String summary(EmployeeEducation e) {
        return "employeeId=" + e.getEmployeeId() + ", active=" + e.getIsActive();
    }

    /** A chosen master value must exist and be active; the value the record already holds may stay as it is. */
    private static void requireActive(Object master, Long id, Long currentId, String rule, String label) {
        if (id == null) return;
        if (master == null) throw new ResourceNotFoundException(label, "id", id);
        if (!id.equals(currentId) && !Boolean.TRUE.equals(activeOf(master))) {
            throw new BusinessRuleException(rule + "_INACTIVE", label + " is not active.");
        }
    }

    private static Boolean activeOf(Object master) {
        if (master instanceof EducationLevel m) return m.getIsActive();
        return Boolean.FALSE;
    }

    private record Refs(Map<Long, EducationLevel> educationLevel) {}

    private Refs refsFor(List<EmployeeEducation> rows) {
        return new Refs(
            byId(educationLevelRepository.findAllById(rows.stream().flatMap(e -> Stream.of(e.getEducationLevelId())).filter(Objects::nonNull).collect(Collectors.toSet())), EducationLevel::getId));
    }

    private static <T> Map<Long, T> byId(List<T> rows, Function<T, Long> id) {
        return rows.stream().collect(Collectors.toMap(id, Function.identity()));
    }

    private static String nameOf(EducationLevel m) {
        return m == null ? null : m.getName();
    }

    private static String nameArOf(EducationLevel m) {
        return m == null ? null : m.getNameAr();
    }

    private EmployeeEducationResponse toResponse(EmployeeEducation e, Refs refs) {
        return EmployeeEducationResponse.builder()
            .id(e.getId())
            .employeeId(e.getEmployeeId())
            .educationLevelId(e.getEducationLevelId())
            .educationLevelName(nameOf(refs.educationLevel().get(e.getEducationLevelId())))
            .educationLevelNameAr(nameArOf(refs.educationLevel().get(e.getEducationLevelId())))
            .qualification(e.getQualification())
            .qualificationAr(e.getQualificationAr())
            .institution(e.getInstitution())
            .startDate(e.getStartDate())
            .endDate(e.getEndDate())
            .isActive(e.getIsActive())
            .version(e.getVersion())
            .build();
    }
}
