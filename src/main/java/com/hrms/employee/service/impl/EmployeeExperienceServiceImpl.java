package com.hrms.employee.service.impl;

import com.hrms.auth.service.AuditTrail;
import com.hrms.common.exception.BadRequestException;
import com.hrms.common.exception.BusinessRuleException;
import com.hrms.common.exception.ResourceNotFoundException;
import com.hrms.common.util.Strings;
import com.hrms.employee.dto.request.EmployeeExperienceRequest;
import com.hrms.employee.dto.response.EmployeeExperienceResponse;
import com.hrms.employee.entity.EmployeeExperience;
import com.hrms.employee.repository.EmployeeExperienceRepository;
import com.hrms.employee.repository.EmployeeRepository;
import com.hrms.employee.service.EmployeeExperienceService;
import com.hrms.employee.service.EmployeeChecks;
import jakarta.persistence.EntityManager;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.util.Comparator;
import java.util.List;

/**
 * Experience records of an employee. Generated by tools/generate_employee_info.py. Writers are HR_ADMIN only (the controller);
 * the audit trail carries ids and never the personal values.
 */
@Slf4j
@Service
@RequiredArgsConstructor
@Transactional(readOnly = true)
public class EmployeeExperienceServiceImpl implements EmployeeExperienceService {

    private static final String TARGET = "EMPLOYEE_EXPERIENCE";

    private final EmployeeExperienceRepository repository;
    private final EmployeeRepository employeeRepository;
    private final AuditTrail audit;
    private final EntityManager entityManager;

    @Override
    public List<EmployeeExperienceResponse> getAll(Long employeeId) {
        EmployeeChecks.requireExists(employeeRepository, employeeId);
        List<EmployeeExperience> rows = repository.findByEmployeeIdOrderByIdAsc(employeeId);
        
        return rows.stream()
            .sorted(Comparator.comparing((EmployeeExperience e) -> !e.getIsActive())
                .thenComparing(Comparator.comparing(EmployeeExperience::getStartDate, Comparator.nullsLast(Comparator.reverseOrder())))
                .thenComparing(EmployeeExperience::getId))
            .map(e -> toResponse(e))
            .toList();
    }

    @Override
    @Transactional
    public EmployeeExperienceResponse add(Long employeeId, EmployeeExperienceRequest request) {
        EmployeeChecks.requireExists(employeeRepository, employeeId);
        validate(request, null);
        EmployeeExperience e = EmployeeExperience.builder().employeeId(employeeId).isActive(true).build();
        apply(e, request);
        EmployeeExperience saved = repository.save(e);
        entityManager.flush();
        log.info("Experience record {} added for employee {}", saved.getId(), employeeId);
        audit.record("EMPLOYEE_EXPERIENCE_ADDED", TARGET, saved.getId(), summary(saved));
        return toResponse(saved);
    }

    @Override
    @Transactional
    public EmployeeExperienceResponse update(Long employeeId, Long id, EmployeeExperienceRequest request) {
        EmployeeExperience existing = find(employeeId, id);
        if (request.getVersion() == null) throw new BadRequestException("version is required to update a record");
        Versions.requireCurrent(request.getVersion(), existing.getVersion());
        if (!existing.getIsActive()) {
            throw new BusinessRuleException("RECORD_INACTIVE", "A deactivated record cannot be edited. Activate it first.");
        }
        validate(request, existing);
        apply(existing, request);
        EmployeeExperience saved = repository.save(existing);
        entityManager.flush(); // so the response carries the incremented version
        audit.record("EMPLOYEE_EXPERIENCE_UPDATED", TARGET, id, summary(saved));
        return toResponse(saved);
    }

    @Override
    @Transactional
    public void deactivate(Long employeeId, Long id) {
        EmployeeExperience e = find(employeeId, id);
        if (!e.getIsActive()) return;
        e.setIsActive(false);
        repository.save(e);
        audit.record("EMPLOYEE_EXPERIENCE_DEACTIVATED", TARGET, id, summary(e));
    }

    @Override
    @Transactional
    public void activate(Long employeeId, Long id) {
        EmployeeExperience e = find(employeeId, id);
        if (e.getIsActive()) return;
        e.setIsActive(true);
        repository.save(e);
        audit.record("EMPLOYEE_EXPERIENCE_ACTIVATED", TARGET, id, summary(e));
    }

    // ── helpers ────────────────────────────────────────────────

    /** The record of THIS employee only: another employee's record is reported as not found. */
    private EmployeeExperience find(Long employeeId, Long id) {
        EmployeeExperience e = repository.findById(id).orElseThrow(() -> new ResourceNotFoundException("Experience record", "id", id));
        if (!e.getEmployeeId().equals(employeeId)) throw new ResourceNotFoundException("Experience record", "id", id);
        return e;
    }

    private void validate(EmployeeExperienceRequest r, EmployeeExperience current) {
        if (r.getStartDate() != null && r.getEndDate() != null && r.getEndDate().isBefore(r.getStartDate())) {
            throw new BusinessRuleException("INVALID_DATE_RANGE", "The end date cannot be before the start date.");
        }
    }

    private static void apply(EmployeeExperience e, EmployeeExperienceRequest r) {
        e.setEmployerName(r.getEmployerName().trim());
        e.setEmployerNameAr(Strings.trimToNull(r.getEmployerNameAr()));
        e.setJobTitle(Strings.trimToNull(r.getJobTitle()));
        e.setPlace(Strings.trimToNull(r.getPlace()));
        e.setStartDate(r.getStartDate());
        e.setEndDate(r.getEndDate());
    }

    private static String summary(EmployeeExperience e) {
        return "employeeId=" + e.getEmployeeId() + ", active=" + e.getIsActive();
    }


    private EmployeeExperienceResponse toResponse(EmployeeExperience e) {
        return EmployeeExperienceResponse.builder()
            .id(e.getId())
            .employeeId(e.getEmployeeId())
            .employerName(e.getEmployerName())
            .employerNameAr(e.getEmployerNameAr())
            .jobTitle(e.getJobTitle())
            .place(e.getPlace())
            .startDate(e.getStartDate())
            .endDate(e.getEndDate())
            .isActive(e.getIsActive())
            .version(e.getVersion())
            .build();
    }
}
