package com.hrms.employee.service.impl;

import com.hrms.auth.service.AuditTrail;
import com.hrms.common.exception.BadRequestException;
import com.hrms.common.exception.BusinessRuleException;
import com.hrms.common.exception.ResourceNotFoundException;
import com.hrms.common.util.Strings;
import com.hrms.employee.dto.request.EmployeeLanguageRequest;
import com.hrms.employee.dto.response.EmployeeLanguageResponse;
import com.hrms.employee.entity.EmployeeLanguage;
import com.hrms.employee.entity.Language;
import com.hrms.employee.repository.LanguageRepository;
import com.hrms.employee.entity.LanguageLevel;
import com.hrms.employee.repository.LanguageLevelRepository;
import com.hrms.employee.repository.EmployeeLanguageRepository;
import com.hrms.employee.repository.EmployeeRepository;
import com.hrms.employee.service.EmployeeLanguageService;
import com.hrms.employee.service.EmployeeChecks;
import jakarta.persistence.EntityManager;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.util.Comparator;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.function.Function;
import java.util.stream.Collectors;
import java.util.stream.Stream;

/**
 * Language records of an employee. Generated by tools/generate_employee_info.py. Writers are HR_ADMIN only (the controller);
 * the audit trail carries ids and never the personal values.
 */
@Slf4j
@Service
@RequiredArgsConstructor
@Transactional(readOnly = true)
public class EmployeeLanguageServiceImpl implements EmployeeLanguageService {

    private static final String TARGET = "EMPLOYEE_LANGUAGE";

    private final EmployeeLanguageRepository repository;
    private final EmployeeRepository employeeRepository;
    private final LanguageRepository languageRepository;
    private final LanguageLevelRepository languageLevelRepository;
    private final AuditTrail audit;
    private final EntityManager entityManager;

    @Override
    public List<EmployeeLanguageResponse> getAll(Long employeeId) {
        EmployeeChecks.requireExists(employeeRepository, employeeId);
        List<EmployeeLanguage> rows = repository.findByEmployeeIdOrderByIdAsc(employeeId);
        Refs refs = refsFor(rows);
        return rows.stream()
            .sorted(Comparator.comparing((EmployeeLanguage e) -> !e.getIsActive())
                .thenComparing(e -> e.getId()))
            .map(e -> toResponse(e, refs))
            .toList();
    }

    @Override
    @Transactional
    public EmployeeLanguageResponse add(Long employeeId, EmployeeLanguageRequest request) {
        EmployeeChecks.requireExists(employeeRepository, employeeId);
        validate(request, null);
        if (repository.existsByEmployeeIdAndLanguageId(employeeId, request.getLanguageId())) {
            throw new BusinessRuleException("DUPLICATE_LANGUAGE",
                "This language is already recorded for the employee. If it was deactivated, activate it instead.");
        }
        EmployeeLanguage e = EmployeeLanguage.builder().employeeId(employeeId).isActive(true).build();
        apply(e, request);
        EmployeeLanguage saved = repository.save(e);
        entityManager.flush();
        log.info("Language record {} added for employee {}", saved.getId(), employeeId);
        audit.record("EMPLOYEE_LANGUAGE_ADDED", TARGET, saved.getId(), summary(saved));
        return toResponse(saved, refsFor(List.of(saved)));
    }

    @Override
    @Transactional
    public EmployeeLanguageResponse update(Long employeeId, Long id, EmployeeLanguageRequest request) {
        EmployeeLanguage existing = find(employeeId, id);
        if (request.getVersion() == null) throw new BadRequestException("version is required to update a record");
        Versions.requireCurrent(request.getVersion(), existing.getVersion());
        if (!existing.getIsActive()) {
            throw new BusinessRuleException("RECORD_INACTIVE", "A deactivated record cannot be edited. Activate it first.");
        }
        validate(request, existing);
        if (!request.getLanguageId().equals(existing.getLanguageId())
                && repository.existsByEmployeeIdAndLanguageIdAndIdNot(employeeId, request.getLanguageId(), id)) {
            throw new BusinessRuleException("DUPLICATE_LANGUAGE",
                "This language is already recorded for the employee. If it was deactivated, activate it instead.");
        }
        apply(existing, request);
        EmployeeLanguage saved = repository.save(existing);
        entityManager.flush(); // so the response carries the incremented version
        audit.record("EMPLOYEE_LANGUAGE_UPDATED", TARGET, id, summary(saved));
        return toResponse(saved, refsFor(List.of(saved)));
    }

    @Override
    @Transactional
    public void deactivate(Long employeeId, Long id) {
        EmployeeLanguage e = find(employeeId, id);
        if (!e.getIsActive()) return;
        e.setIsActive(false);
        repository.save(e);
        audit.record("EMPLOYEE_LANGUAGE_DEACTIVATED", TARGET, id, summary(e));
    }

    @Override
    @Transactional
    public void activate(Long employeeId, Long id) {
        EmployeeLanguage e = find(employeeId, id);
        if (e.getIsActive()) return;
        e.setIsActive(true);
        repository.save(e);
        audit.record("EMPLOYEE_LANGUAGE_ACTIVATED", TARGET, id, summary(e));
    }

    // ── helpers ────────────────────────────────────────────────

    /** The record of THIS employee only: another employee's record is reported as not found. */
    private EmployeeLanguage find(Long employeeId, Long id) {
        EmployeeLanguage e = repository.findById(id).orElseThrow(() -> new ResourceNotFoundException("Language record", "id", id));
        if (!e.getEmployeeId().equals(employeeId)) throw new ResourceNotFoundException("Language record", "id", id);
        return e;
    }

    private void validate(EmployeeLanguageRequest r, EmployeeLanguage current) {
        requireActive(r.getLanguageId() == null ? null : languageRepository.findById(r.getLanguageId()).orElse(null), r.getLanguageId(), current == null ? null : current.getLanguageId(), "LANGUAGE", "Language");
        requireActive(r.getReadLevelId() == null ? null : languageLevelRepository.findById(r.getReadLevelId()).orElse(null), r.getReadLevelId(), current == null ? null : current.getReadLevelId(), "LANGUAGE_LEVEL", "Reading level");
        requireActive(r.getWriteLevelId() == null ? null : languageLevelRepository.findById(r.getWriteLevelId()).orElse(null), r.getWriteLevelId(), current == null ? null : current.getWriteLevelId(), "LANGUAGE_LEVEL", "Writing level");
        requireActive(r.getSpeakLevelId() == null ? null : languageLevelRepository.findById(r.getSpeakLevelId()).orElse(null), r.getSpeakLevelId(), current == null ? null : current.getSpeakLevelId(), "LANGUAGE_LEVEL", "Speaking level");
    }

    private static void apply(EmployeeLanguage e, EmployeeLanguageRequest r) {
        e.setLanguageId(r.getLanguageId());
        e.setReadLevelId(r.getReadLevelId());
        e.setWriteLevelId(r.getWriteLevelId());
        e.setSpeakLevelId(r.getSpeakLevelId());
    }

    private static String summary(EmployeeLanguage e) {
        return "employeeId=" + e.getEmployeeId() + ", active=" + e.getIsActive();
    }

    /** A chosen master value must exist and be active; the value the record already holds may stay as it is. */
    private static void requireActive(Object master, Long id, Long currentId, String rule, String label) {
        if (id == null) return;
        if (master == null) throw new ResourceNotFoundException(label, "id", id);
        if (!id.equals(currentId) && !Boolean.TRUE.equals(activeOf(master))) {
            throw new BusinessRuleException(rule + "_INACTIVE", label + " is not active.");
        }
    }

    private static Boolean activeOf(Object master) {
        if (master instanceof Language m) return m.getIsActive();
        if (master instanceof LanguageLevel m) return m.getIsActive();
        return Boolean.FALSE;
    }

    private record Refs(Map<Long, Language> language, Map<Long, LanguageLevel> languageLevel) {}

    private Refs refsFor(List<EmployeeLanguage> rows) {
        return new Refs(
            byId(languageRepository.findAllById(rows.stream().flatMap(e -> Stream.of(e.getLanguageId())).filter(Objects::nonNull).collect(Collectors.toSet())), Language::getId),
            byId(languageLevelRepository.findAllById(rows.stream().flatMap(e -> Stream.of(e.getReadLevelId(), e.getWriteLevelId(), e.getSpeakLevelId())).filter(Objects::nonNull).collect(Collectors.toSet())), LanguageLevel::getId));
    }

    private static <T> Map<Long, T> byId(List<T> rows, Function<T, Long> id) {
        return rows.stream().collect(Collectors.toMap(id, Function.identity()));
    }

    private static String nameOf(Language m) {
        return m == null ? null : m.getName();
    }

    private static String nameArOf(Language m) {
        return m == null ? null : m.getNameAr();
    }

    private static String nameOf(LanguageLevel m) {
        return m == null ? null : m.getName();
    }

    private static String nameArOf(LanguageLevel m) {
        return m == null ? null : m.getNameAr();
    }

    private EmployeeLanguageResponse toResponse(EmployeeLanguage e, Refs refs) {
        return EmployeeLanguageResponse.builder()
            .id(e.getId())
            .employeeId(e.getEmployeeId())
            .languageId(e.getLanguageId())
            .languageName(nameOf(refs.language().get(e.getLanguageId())))
            .languageNameAr(nameArOf(refs.language().get(e.getLanguageId())))
            .readLevelId(e.getReadLevelId())
            .readLevelName(nameOf(refs.languageLevel().get(e.getReadLevelId())))
            .readLevelNameAr(nameArOf(refs.languageLevel().get(e.getReadLevelId())))
            .writeLevelId(e.getWriteLevelId())
            .writeLevelName(nameOf(refs.languageLevel().get(e.getWriteLevelId())))
            .writeLevelNameAr(nameArOf(refs.languageLevel().get(e.getWriteLevelId())))
            .speakLevelId(e.getSpeakLevelId())
            .speakLevelName(nameOf(refs.languageLevel().get(e.getSpeakLevelId())))
            .speakLevelNameAr(nameArOf(refs.languageLevel().get(e.getSpeakLevelId())))
            .isActive(e.getIsActive())
            .version(e.getVersion())
            .build();
    }
}
