package com.hrms.employee.service.impl;

import com.hrms.auth.service.AuditTrail;
import com.hrms.common.exception.BadRequestException;
import com.hrms.common.exception.BusinessRuleException;
import com.hrms.common.exception.ResourceNotFoundException;
import com.hrms.common.util.Strings;
import com.hrms.employee.dto.request.EmployeeReferenceRequest;
import com.hrms.employee.dto.response.EmployeeReferenceResponse;
import com.hrms.employee.entity.EmployeeReference;
import com.hrms.employee.repository.EmployeeReferenceRepository;
import com.hrms.employee.repository.EmployeeRepository;
import com.hrms.employee.service.EmployeeReferenceService;
import com.hrms.employee.service.EmployeeChecks;
import jakarta.persistence.EntityManager;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.util.Comparator;
import java.util.List;

/**
 * References of an employee. Generated by tools/generate_employee_info.py. Writers are HR_ADMIN only (the controller);
 * the audit trail carries ids and never the personal values.
 */
@Slf4j
@Service
@RequiredArgsConstructor
@Transactional(readOnly = true)
public class EmployeeReferenceServiceImpl implements EmployeeReferenceService {

    private static final String TARGET = "EMPLOYEE_REFERENCE";

    private final EmployeeReferenceRepository repository;
    private final EmployeeRepository employeeRepository;
    private final AuditTrail audit;
    private final EntityManager entityManager;

    @Override
    public List<EmployeeReferenceResponse> getAll(Long employeeId) {
        EmployeeChecks.requireExists(employeeRepository, employeeId);
        List<EmployeeReference> rows = repository.findByEmployeeIdOrderByIdAsc(employeeId);
        
        return rows.stream()
            .sorted(Comparator.comparing((EmployeeReference e) -> !e.getIsActive())
                .thenComparing(e -> e.getId()))
            .map(e -> toResponse(e))
            .toList();
    }

    @Override
    @Transactional
    public EmployeeReferenceResponse add(Long employeeId, EmployeeReferenceRequest request) {
        EmployeeChecks.requireExists(employeeRepository, employeeId);
        validate(request, null);
        EmployeeReference e = EmployeeReference.builder().employeeId(employeeId).isActive(true).build();
        apply(e, request);
        EmployeeReference saved = repository.save(e);
        entityManager.flush();
        log.info("Reference {} added for employee {}", saved.getId(), employeeId);
        audit.record("EMPLOYEE_REFERENCE_ADDED", TARGET, saved.getId(), summary(saved));
        return toResponse(saved);
    }

    @Override
    @Transactional
    public EmployeeReferenceResponse update(Long employeeId, Long id, EmployeeReferenceRequest request) {
        EmployeeReference existing = find(employeeId, id);
        if (request.getVersion() == null) throw new BadRequestException("version is required to update a record");
        Versions.requireCurrent(request.getVersion(), existing.getVersion());
        if (!existing.getIsActive()) {
            throw new BusinessRuleException("RECORD_INACTIVE", "A deactivated record cannot be edited. Activate it first.");
        }
        validate(request, existing);
        apply(existing, request);
        EmployeeReference saved = repository.save(existing);
        entityManager.flush(); // so the response carries the incremented version
        audit.record("EMPLOYEE_REFERENCE_UPDATED", TARGET, id, summary(saved));
        return toResponse(saved);
    }

    @Override
    @Transactional
    public void deactivate(Long employeeId, Long id) {
        EmployeeReference e = find(employeeId, id);
        if (!e.getIsActive()) return;
        e.setIsActive(false);
        repository.save(e);
        audit.record("EMPLOYEE_REFERENCE_DEACTIVATED", TARGET, id, summary(e));
    }

    @Override
    @Transactional
    public void activate(Long employeeId, Long id) {
        EmployeeReference e = find(employeeId, id);
        if (e.getIsActive()) return;
        e.setIsActive(true);
        repository.save(e);
        audit.record("EMPLOYEE_REFERENCE_ACTIVATED", TARGET, id, summary(e));
    }

    // ── helpers ────────────────────────────────────────────────

    /** The record of THIS employee only: another employee's record is reported as not found. */
    private EmployeeReference find(Long employeeId, Long id) {
        EmployeeReference e = repository.findById(id).orElseThrow(() -> new ResourceNotFoundException("Reference", "id", id));
        if (!e.getEmployeeId().equals(employeeId)) throw new ResourceNotFoundException("Reference", "id", id);
        return e;
    }

    private void validate(EmployeeReferenceRequest r, EmployeeReference current) {
        // nothing beyond bean validation
    }

    private static void apply(EmployeeReference e, EmployeeReferenceRequest r) {
        e.setFirstName(r.getFirstName().trim());
        e.setMiddleName(Strings.trimToNull(r.getMiddleName()));
        e.setLastName(Strings.trimToNull(r.getLastName()));
        e.setFirstNameAr(Strings.trimToNull(r.getFirstNameAr()));
        e.setMiddleNameAr(Strings.trimToNull(r.getMiddleNameAr()));
        e.setLastNameAr(Strings.trimToNull(r.getLastNameAr()));
        e.setJobTitle(Strings.trimToNull(r.getJobTitle()));
        e.setAddress(Strings.trimToNull(r.getAddress()));
        e.setPhone(Strings.trimToNull(r.getPhone()));
        e.setEmail(Strings.trimToNull(r.getEmail()));
    }

    private static String summary(EmployeeReference e) {
        return "employeeId=" + e.getEmployeeId() + ", active=" + e.getIsActive();
    }


    private EmployeeReferenceResponse toResponse(EmployeeReference e) {
        return EmployeeReferenceResponse.builder()
            .id(e.getId())
            .employeeId(e.getEmployeeId())
            .firstName(e.getFirstName())
            .middleName(e.getMiddleName())
            .lastName(e.getLastName())
            .firstNameAr(e.getFirstNameAr())
            .middleNameAr(e.getMiddleNameAr())
            .lastNameAr(e.getLastNameAr())
            .jobTitle(e.getJobTitle())
            .address(e.getAddress())
            .phone(e.getPhone())
            .email(e.getEmail())
            .isActive(e.getIsActive())
            .version(e.getVersion())
            .build();
    }
}
