package com.hrms.employee.service.impl;

import com.hrms.auth.service.AuditTrail;
import com.hrms.common.exception.BadRequestException;
import com.hrms.common.exception.BusinessRuleException;
import com.hrms.common.exception.ResourceNotFoundException;
import com.hrms.common.util.Strings;
import com.hrms.employee.dto.request.EmployeeTrainingRequest;
import com.hrms.employee.dto.response.EmployeeTrainingResponse;
import com.hrms.employee.entity.EmployeeTraining;
import com.hrms.employee.repository.EmployeeTrainingRepository;
import com.hrms.employee.repository.EmployeeRepository;
import com.hrms.employee.service.EmployeeTrainingService;
import com.hrms.employee.service.EmployeeChecks;
import jakarta.persistence.EntityManager;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.util.Comparator;
import java.util.List;

/**
 * Training records of an employee. Generated by tools/generate_employee_info.py. Writers are HR_ADMIN only (the controller);
 * the audit trail carries ids and never the personal values.
 */
@Slf4j
@Service
@RequiredArgsConstructor
@Transactional(readOnly = true)
public class EmployeeTrainingServiceImpl implements EmployeeTrainingService {

    private static final String TARGET = "EMPLOYEE_TRAINING";

    private final EmployeeTrainingRepository repository;
    private final EmployeeRepository employeeRepository;
    private final AuditTrail audit;
    private final EntityManager entityManager;

    @Override
    public List<EmployeeTrainingResponse> getAll(Long employeeId) {
        EmployeeChecks.requireExists(employeeRepository, employeeId);
        List<EmployeeTraining> rows = repository.findByEmployeeIdOrderByIdAsc(employeeId);
        
        return rows.stream()
            .sorted(Comparator.comparing((EmployeeTraining e) -> !e.getIsActive())
                .thenComparing(Comparator.comparing(EmployeeTraining::getStartDate, Comparator.nullsLast(Comparator.reverseOrder())))
                .thenComparing(EmployeeTraining::getId))
            .map(e -> toResponse(e))
            .toList();
    }

    @Override
    @Transactional
    public EmployeeTrainingResponse add(Long employeeId, EmployeeTrainingRequest request) {
        EmployeeChecks.requireExists(employeeRepository, employeeId);
        validate(request, null);
        EmployeeTraining e = EmployeeTraining.builder().employeeId(employeeId).isActive(true).build();
        apply(e, request);
        EmployeeTraining saved = repository.save(e);
        entityManager.flush();
        log.info("Training record {} added for employee {}", saved.getId(), employeeId);
        audit.record("EMPLOYEE_TRAINING_ADDED", TARGET, saved.getId(), summary(saved));
        return toResponse(saved);
    }

    @Override
    @Transactional
    public EmployeeTrainingResponse update(Long employeeId, Long id, EmployeeTrainingRequest request) {
        EmployeeTraining existing = find(employeeId, id);
        if (request.getVersion() == null) throw new BadRequestException("version is required to update a record");
        Versions.requireCurrent(request.getVersion(), existing.getVersion());
        if (!existing.getIsActive()) {
            throw new BusinessRuleException("RECORD_INACTIVE", "A deactivated record cannot be edited. Activate it first.");
        }
        validate(request, existing);
        apply(existing, request);
        EmployeeTraining saved = repository.save(existing);
        entityManager.flush(); // so the response carries the incremented version
        audit.record("EMPLOYEE_TRAINING_UPDATED", TARGET, id, summary(saved));
        return toResponse(saved);
    }

    @Override
    @Transactional
    public void deactivate(Long employeeId, Long id) {
        EmployeeTraining e = find(employeeId, id);
        if (!e.getIsActive()) return;
        e.setIsActive(false);
        repository.save(e);
        audit.record("EMPLOYEE_TRAINING_DEACTIVATED", TARGET, id, summary(e));
    }

    @Override
    @Transactional
    public void activate(Long employeeId, Long id) {
        EmployeeTraining e = find(employeeId, id);
        if (e.getIsActive()) return;
        e.setIsActive(true);
        repository.save(e);
        audit.record("EMPLOYEE_TRAINING_ACTIVATED", TARGET, id, summary(e));
    }

    // ── helpers ────────────────────────────────────────────────

    /** The record of THIS employee only: another employee's record is reported as not found. */
    private EmployeeTraining find(Long employeeId, Long id) {
        EmployeeTraining e = repository.findById(id).orElseThrow(() -> new ResourceNotFoundException("Training record", "id", id));
        if (!e.getEmployeeId().equals(employeeId)) throw new ResourceNotFoundException("Training record", "id", id);
        return e;
    }

    private void validate(EmployeeTrainingRequest r, EmployeeTraining current) {
        if (r.getStartDate() != null && r.getEndDate() != null && r.getEndDate().isBefore(r.getStartDate())) {
            throw new BusinessRuleException("INVALID_DATE_RANGE", "The end date cannot be before the start date.");
        }
    }

    private static void apply(EmployeeTraining e, EmployeeTrainingRequest r) {
        e.setCourseName(r.getCourseName().trim());
        e.setCourseNameAr(Strings.trimToNull(r.getCourseNameAr()));
        e.setProvider(Strings.trimToNull(r.getProvider()));
        e.setStartDate(r.getStartDate());
        e.setEndDate(r.getEndDate());
    }

    private static String summary(EmployeeTraining e) {
        return "employeeId=" + e.getEmployeeId() + ", active=" + e.getIsActive();
    }


    private EmployeeTrainingResponse toResponse(EmployeeTraining e) {
        return EmployeeTrainingResponse.builder()
            .id(e.getId())
            .employeeId(e.getEmployeeId())
            .courseName(e.getCourseName())
            .courseNameAr(e.getCourseNameAr())
            .provider(e.getProvider())
            .startDate(e.getStartDate())
            .endDate(e.getEndDate())
            .isActive(e.getIsActive())
            .version(e.getVersion())
            .build();
    }
}
