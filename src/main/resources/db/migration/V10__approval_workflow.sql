-- ===== 4. Request history (append-only: the code never updates or deletes a row) =====
-- ACTOR_EMPLOYEE_ID is NULL for system actions (AUTO_ROUTED) and for a SYSTEM_ADMIN account with no employee record.
CREATE TABLE HRMS.REQUEST_HISTORY (
    HISTORY_ID        NUMBER(20,0) NOT NULL,
    REQUEST_TYPE      VARCHAR2(30 CHAR) NOT NULL,
    REQUEST_ID        NUMBER(20,0) NOT NULL,
    STEP_KEY          VARCHAR2(30 CHAR),
    ACTION            VARCHAR2(20 CHAR) NOT NULL,
    ACTOR_EMPLOYEE_ID NUMBER(20,0),
    ACTOR_ROLE        VARCHAR2(30 CHAR),
    COMMENT_TEXT      VARCHAR2(500 CHAR),
    REASON_CODE       VARCHAR2(30 CHAR),
    ACTED_AT          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_REQUEST_HISTORY  PRIMARY KEY (HISTORY_ID),
    CONSTRAINT CHK_RH_TYPE         CHECK (REQUEST_TYPE IN ('LEAVE','ATTENDANCE_REGULARIZATION','OVERTIME','RECRUITMENT_REQUISITION')),
    CONSTRAINT CHK_RH_ACTION       CHECK (ACTION IN ('SUBMITTED','FORWARDED','APPROVED','REJECTED','CANCELLED','OVERRIDDEN','AUTO_ROUTED')),
    CONSTRAINT FK_RH_ACTOR         FOREIGN KEY (ACTOR_EMPLOYEE_ID) REFERENCES HRMS.EMPLOYEES(EMPLOYEE_ID)
);
CREATE INDEX IDX_RH_REQUEST ON HRMS.REQUEST_HISTORY (REQUEST_TYPE, REQUEST_ID);
CREATE INDEX IDX_RH_ACTOR   ON HRMS.REQUEST_HISTORY (ACTOR_EMPLOYEE_ID);

-- ===== 5. Leave requests carry their workflow position =====
-- STAGE: PENDING_<step key> while open, then APPROVED / REJECTED / CANCELLED. The old STATUS column keeps its meaning.
-- TARGET_DEPARTMENT_ID is chosen by the branch manager; CURRENT_APPROVER_* is the inbox column, refreshed on each move.
ALTER TABLE HRMS.LEAVE_REQUESTS ADD (
    WORKFLOW_DEFINITION_ID       NUMBER(20,0),
    FLOWABLE_PROCESS_INSTANCE_ID VARCHAR2(64 CHAR),
    STAGE                        VARCHAR2(40 CHAR),
    TARGET_DEPARTMENT_ID         NUMBER(20,0),
    CURRENT_STEP_KEY             VARCHAR2(30 CHAR),
    CURRENT_APPROVER_EMPLOYEE_ID NUMBER(20,0),
    CURRENT_APPROVER_ROLE        VARCHAR2(30 CHAR)
);
ALTER TABLE HRMS.LEAVE_REQUESTS ADD CONSTRAINT CHK_LR_STAGE
    CHECK (STAGE IS NULL OR REGEXP_LIKE(STAGE, '^(PENDING_[A-Z0-9_]+|DRAFT|APPROVED|REJECTED|CANCELLED)$'));
ALTER TABLE HRMS.LEAVE_REQUESTS ADD CONSTRAINT FK_LR_WF_DEFINITION
    FOREIGN KEY (WORKFLOW_DEFINITION_ID) REFERENCES HRMS.WORKFLOW_DEFINITIONS(DEFINITION_ID);
ALTER TABLE HRMS.LEAVE_REQUESTS ADD CONSTRAINT FK_LR_TARGET_DEPT
    FOREIGN KEY (TARGET_DEPARTMENT_ID) REFERENCES HRMS.DEPARTMENTS(DEPT_ID);
ALTER TABLE HRMS.LEAVE_REQUESTS ADD CONSTRAINT FK_LR_CUR_APPROVER
    FOREIGN KEY (CURRENT_APPROVER_EMPLOYEE_ID) REFERENCES HRMS.EMPLOYEES(EMPLOYEE_ID);
CREATE INDEX IDX_LR_WF_DEFINITION  ON HRMS.LEAVE_REQUESTS (WORKFLOW_DEFINITION_ID);
CREATE INDEX IDX_LR_TARGET_DEPT    ON HRMS.LEAVE_REQUESTS (TARGET_DEPARTMENT_ID);
CREATE INDEX IDX_LR_CUR_APPROVER   ON HRMS.LEAVE_REQUESTS (CURRENT_APPROVER_EMPLOYEE_ID);
CREATE INDEX IDX_LR_CUR_ROLE       ON HRMS.LEAVE_REQUESTS (CURRENT_APPROVER_ROLE);
CREATE INDEX IDX_LR_STAGE          ON HRMS.LEAVE_REQUESTS (STAGE);

-- ===== 6. The GENERAL_MANAGER role =====
-- Same shape as SYSTEM_ADMIN: a ROLES row plus a place in the AUTH_USERS.ROLE check. Dev already has the named
-- CK_AUTH_USERS_ROLE; a database built from V1 still has the old unnamed 3-role check, so drop whichever check
-- constrains ROLE and recreate one named check with every role (existing 10 + GENERAL_MANAGER).
INSERT INTO HRMS.ROLES (ROLE_NAME, DESCRIPTION)
SELECT 'GENERAL_MANAGER', 'Final approver for requests that reach the general manager'
  FROM DUAL
 WHERE NOT EXISTS (SELECT 1 FROM HRMS.ROLES WHERE ROLE_NAME = 'GENERAL_MANAGER');

-- Brief DDL window: between the DROP and the ADD of the check, AUTH_USERS.ROLE is unconstrained for a few
-- milliseconds. Run V10 with the backend stopped (as for every migration).
DECLARE
  v_found NUMBER := 0;
BEGIN
  -- 1. The known name (dev and any DB that already ran the SYSTEM_ADMIN script).
  FOR c IN (SELECT CONSTRAINT_NAME FROM ALL_CONSTRAINTS
             WHERE OWNER = 'HRMS' AND TABLE_NAME = 'AUTH_USERS' AND CONSTRAINT_TYPE = 'C'
               AND CONSTRAINT_NAME = 'CK_AUTH_USERS_ROLE') LOOP
    EXECUTE IMMEDIATE 'ALTER TABLE HRMS.AUTH_USERS DROP CONSTRAINT "' || c.CONSTRAINT_NAME || '"';
    v_found := 1;
  END LOOP;
  -- 2. Fallback: the unnamed V1 check, found by its condition on the ROLE column only.
  IF v_found = 0 THEN
    FOR c IN (SELECT CONSTRAINT_NAME FROM ALL_CONSTRAINTS
               WHERE OWNER = 'HRMS' AND TABLE_NAME = 'AUTH_USERS' AND CONSTRAINT_TYPE = 'C'
                 AND REGEXP_LIKE(UPPER(SEARCH_CONDITION_VC), '^[[:space:](]*"?ROLE"?[[:space:]]+IN[[:space:]]*\(')) LOOP
      EXECUTE IMMEDIATE 'ALTER TABLE HRMS.AUTH_USERS DROP CONSTRAINT "' || c.CONSTRAINT_NAME || '"';
    END LOOP;
  END IF;
  EXECUTE IMMEDIATE q'[ALTER TABLE HRMS.AUTH_USERS ADD CONSTRAINT CK_AUTH_USERS_ROLE CHECK ("ROLE" IN
    ('SYSTEM_ADMIN','HR_ADMIN','HR_MANAGER','GENERAL_MANAGER','EMPLOYEE','REPORTING_MANAGER',
     'ATTENDANCE_OFFICER','PAYROLL_OFFICER','PAYROLL_APPROVER','FINANCE_USER','AUDITOR'))]';
END;
