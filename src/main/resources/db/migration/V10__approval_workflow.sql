-- V10: approval workflow (leave first) -- department secretary, request routing columns, the workflow
-- settings tables, the request history, and the GENERAL_MANAGER role.
-- Not applied yet. Run by hand on HRMS (Flyway is validate-only), then record it with db/flyway_record_v10.sql.
-- Rollback: db/rollback_V10.sql. Menu: db/workflow_menu.sql (run after the backend and frontend are deployed).
-- Additive only: every new column on an existing table is NULLABLE, so existing rows keep working; a request with
-- WORKFLOW_DEFINITION_ID NULL is a legacy request and keeps the old one-step approval.
-- Conventions: IDs come from sequences (no triggers), flags are NUMBER(1) with CHECK, VARCHAR2 uses CHAR semantics.
-- Column names differ from spec section 6 where Oracle reserves the word: COMMENT -> COMMENT_TEXT, POSITION -> POSITION_NO.
-- Rules that need the code (approver is not the requester, who may act, target department must be active)
-- live in the service layer; the constraints below are the last line of defence.

-- ===== 1. Sequences =====
CREATE SEQUENCE HRMS.SEQ_WORKFLOW_DEFINITIONS INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999 NOCYCLE NOCACHE NOORDER;
CREATE SEQUENCE HRMS.SEQ_WORKFLOW_STEPS       INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999 NOCYCLE NOCACHE NOORDER;
CREATE SEQUENCE HRMS.SEQ_WORKFLOW_ROUTES      INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999 NOCYCLE NOCACHE NOORDER;
CREATE SEQUENCE HRMS.SEQ_REQUEST_HISTORY      INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999 NOCYCLE NOCACHE NOORDER;

-- ===== 2. A department has one secretary =====
-- One secretary per department; one person may be secretary of several departments (no unique index on it).
ALTER TABLE HRMS.DEPARTMENTS ADD (SECRETARY_EMPLOYEE_ID NUMBER(20,0));
ALTER TABLE HRMS.DEPARTMENTS ADD CONSTRAINT FK_DEPT_SECRETARY
    FOREIGN KEY (SECRETARY_EMPLOYEE_ID) REFERENCES HRMS.EMPLOYEES(EMPLOYEE_ID);
CREATE INDEX IDX_DEPT_SECRETARY_ID ON HRMS.DEPARTMENTS (SECRETARY_EMPLOYEE_ID);

-- ===== 3. Workflow definitions, steps, routes, settings =====
-- One row per published version of a request type's flow. Exactly one ACTIVE per type.
CREATE TABLE HRMS.WORKFLOW_DEFINITIONS (
    DEFINITION_ID                  NUMBER(20,0) NOT NULL,
    REQUEST_TYPE                   VARCHAR2(30 CHAR) NOT NULL,
    VERSION_NO                     NUMBER(6,0) NOT NULL,
    STATUS                         VARCHAR2(10 CHAR) DEFAULT 'DRAFT' NOT NULL,
    FLOWABLE_DEPLOYMENT_ID         VARCHAR2(64 CHAR),
    FLOWABLE_PROCESS_DEFINITION_ID VARCHAR2(128 CHAR),
    PUBLISHED_BY                   VARCHAR2(50 CHAR),
    PUBLISHED_AT                   TIMESTAMP,
    CREATED_BY                     VARCHAR2(50 CHAR),
    CREATED_AT                     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_BY                     VARCHAR2(50 CHAR),
    UPDATED_AT                     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    VERSION                        NUMBER(10,0) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_WF_DEFINITIONS   PRIMARY KEY (DEFINITION_ID),
    CONSTRAINT UQ_WF_DEF_TYPE_VER  UNIQUE (REQUEST_TYPE, VERSION_NO),
    CONSTRAINT CHK_WF_DEF_TYPE     CHECK (REQUEST_TYPE IN ('LEAVE','ATTENDANCE_REGULARIZATION','OVERTIME','RECRUITMENT_REQUISITION')),
    CONSTRAINT CHK_WF_DEF_STATUS   CHECK (STATUS IN ('DRAFT','ACTIVE','RETIRED'))
);
-- At most one ACTIVE definition per request type.
CREATE UNIQUE INDEX UQ_WF_DEF_ACTIVE ON HRMS.WORKFLOW_DEFINITIONS (
    CASE WHEN STATUS = 'ACTIVE' THEN REQUEST_TYPE END);

CREATE TABLE HRMS.WORKFLOW_STEPS (
    STEP_ID                  NUMBER(20,0) NOT NULL,
    DEFINITION_ID            NUMBER(20,0) NOT NULL,
    STEP_KEY                 VARCHAR2(30 CHAR) NOT NULL,
    POSITION_NO              NUMBER(3,0) NOT NULL,
    LABEL_EN                 VARCHAR2(100 CHAR) NOT NULL,
    LABEL_AR                 NVARCHAR2(200) NOT NULL,
    APPROVER_TYPE            VARCHAR2(30 CHAR) NOT NULL,
    APPROVER_ROLE            VARCHAR2(30 CHAR),
    REQUIRES_DOCUMENT_REVIEW NUMBER(1,0) DEFAULT 0 NOT NULL,
    PICKS_TARGET_DEPARTMENT  NUMBER(1,0) DEFAULT 0 NOT NULL,
    CREATED_BY               VARCHAR2(50 CHAR),
    CREATED_AT               TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_BY               VARCHAR2(50 CHAR),
    UPDATED_AT               TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    VERSION                  NUMBER(10,0) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_WF_STEPS         PRIMARY KEY (STEP_ID),
    CONSTRAINT UQ_WF_STEP_KEY      UNIQUE (DEFINITION_ID, STEP_KEY),
    CONSTRAINT UQ_WF_STEP_POS      UNIQUE (DEFINITION_ID, POSITION_NO),
    CONSTRAINT CHK_WF_STEP_KEY     CHECK (REGEXP_LIKE(STEP_KEY, '^[A-Z0-9_]+$')),
    CONSTRAINT CHK_WF_STEP_TYPE    CHECK (APPROVER_TYPE IN ('BRANCH_MANAGER','DEPARTMENT_SECRETARY','DEPARTMENT_HEAD','ROLE')),
    CONSTRAINT CHK_WF_STEP_ROLE    CHECK (APPROVER_ROLE IS NULL OR APPROVER_ROLE IN ('HR_ADMIN','HR_MANAGER','GENERAL_MANAGER')),
    CONSTRAINT CHK_WF_STEP_ROLE_TY CHECK ((APPROVER_TYPE = 'ROLE' AND APPROVER_ROLE IS NOT NULL)
                                       OR (APPROVER_TYPE <> 'ROLE' AND APPROVER_ROLE IS NULL)),
    CONSTRAINT CHK_WF_STEP_FLAGS   CHECK (REQUIRES_DOCUMENT_REVIEW IN (0,1) AND PICKS_TARGET_DEPARTMENT IN (0,1)),
    CONSTRAINT FK_WF_STEP_DEF      FOREIGN KEY (DEFINITION_ID) REFERENCES HRMS.WORKFLOW_DEFINITIONS(DEFINITION_ID)
);
-- DEFINITION_ID is the leading column of UQ_WF_STEP_KEY, which already serves the FK.

CREATE TABLE HRMS.WORKFLOW_ROUTES (
    ROUTE_ID       NUMBER(20,0) NOT NULL,
    STEP_ID        NUMBER(20,0) NOT NULL,
    OUTCOME        VARCHAR2(10 CHAR) NOT NULL,
    COND_FIELD     VARCHAR2(30 CHAR),
    COND_OPERATOR  VARCHAR2(2 CHAR),
    COND_VALUE     NUMBER(14,3),
    TARGET         VARCHAR2(30 CHAR) NOT NULL,
    POSITION_NO    NUMBER(3,0) DEFAULT 1 NOT NULL,
    CREATED_BY     VARCHAR2(50 CHAR),
    CREATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_BY     VARCHAR2(50 CHAR),
    UPDATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    VERSION        NUMBER(10,0) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_WF_ROUTES        PRIMARY KEY (ROUTE_ID),
    CONSTRAINT UQ_WF_ROUTE_POS     UNIQUE (STEP_ID, POSITION_NO),
    CONSTRAINT CHK_WF_ROUTE_OUT    CHECK (OUTCOME IN ('FORWARD','APPROVE','REJECT')),
    CONSTRAINT CHK_WF_ROUTE_OP     CHECK (COND_OPERATOR IS NULL OR COND_OPERATOR IN ('>','>=','<','<=','=','<>')),
    -- A condition is all three parts or none (none = unconditional route).
    CONSTRAINT CHK_WF_ROUTE_COND   CHECK ((COND_FIELD IS NULL AND COND_OPERATOR IS NULL AND COND_VALUE IS NULL)
                                       OR (COND_FIELD IS NOT NULL AND COND_OPERATOR IS NOT NULL AND COND_VALUE IS NOT NULL)),
    CONSTRAINT CHK_WF_ROUTE_TARGET CHECK (REGEXP_LIKE(TARGET, '^[A-Z0-9_]+$')),
    CONSTRAINT FK_WF_ROUTE_STEP    FOREIGN KEY (STEP_ID) REFERENCES HRMS.WORKFLOW_STEPS(STEP_ID)
);
-- STEP_ID is the leading column of UQ_WF_ROUTE_POS, which already serves the FK.

-- Global switches. Values are the text 'true' / 'false' (or a later key's own value). Both keys start off.
CREATE TABLE HRMS.WORKFLOW_SETTINGS (
    SETTING_KEY    VARCHAR2(60 CHAR) NOT NULL,
    SETTING_VALUE  VARCHAR2(200 CHAR) NOT NULL,
    CREATED_BY     VARCHAR2(50 CHAR),
    CREATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_BY     VARCHAR2(50 CHAR),
    UPDATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    VERSION        NUMBER(10,0) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_WF_SETTINGS      PRIMARY KEY (SETTING_KEY),
    CONSTRAINT CHK_WF_SET_KEY      CHECK (REGEXP_LIKE(SETTING_KEY, '^[A-Z0-9_]+$'))
);
