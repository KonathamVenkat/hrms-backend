-- DESIGNATIONS.GRADE_LEVEL. Not applied yet. Run by hand on HRMS (Flyway is validate-only), then record it with
-- db/flyway_record_v12.sql. Rollback: db/rollback_V12.sql.
-- Additive: nothing existing is changed. GRADES and DESIGNATIONS are NOT linked to it yet, and DESIGNATIONS.GRADE_LEVEL
-- stays. TRACK has no CHECK on purpose (the meaning of the letters P/M/E/S is still to be confirmed) and is left empty.
-- The names are the codes for now: HR edits them once the levels are named.
CREATE TABLE HRMS.GRADE_LEVELS (
	GRADE_LEVEL_ID NUMBER(20,0) NOT NULL,
	LEVELS_CODE VARCHAR2(10 CHAR) NOT NULL,
	LEVELS_NAME VARCHAR2(200 CHAR) NOT NULL,
	LEVELS_NAME_AR NVARCHAR2(200) NOT NULL,
	TRACK VARCHAR2(20 CHAR),
	SORT_ORDER NUMBER(4,0),
	IS_ACTIVE NUMBER(1,0) DEFAULT 1 NOT NULL,
	CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
	UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
	VERSION NUMBER(10,0) DEFAULT 0 NOT NULL,
	CONSTRAINT PK_GRADE_LEVELS PRIMARY KEY (GRADE_LEVEL_ID),
	CONSTRAINT UQ_GRADE_LEVELS_CODE UNIQUE (LEVELS_CODE),
	CONSTRAINT CHK_GRADE_LEVELS_ACTIVE CHECK (IS_ACTIVE IN (0,1))
);

CREATE SEQUENCE HRMS.SEQ_GRADE_LEVELS INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999 NOCYCLE NOCACHE NOORDER;

-- The nine values typed in DESIGNATIONS.GRADE_LEVEL on the dev DB on 2026-10-28.
INSERT INTO HRMS.GRADE_LEVELS (GRADE_LEVEL_ID, LEVELS_CODE, LEVELS_NAME, LEVELS_NAME_AR, SORT_ORDER)
SELECT HRMS.SEQ_GRADE_LEVELS.NEXTVAL, c, c, c, o
  FROM (SELECT 'E0' c, 1 o FROM DUAL UNION ALL SELECT 'E1', 2 FROM DUAL
        UNION ALL SELECT 'M1', 3 FROM DUAL UNION ALL SELECT 'M2', 4 FROM DUAL
        UNION ALL SELECT 'P1', 5 FROM DUAL UNION ALL SELECT 'P2', 6 FROM DUAL UNION ALL SELECT 'P3', 7 FROM DUAL
        UNION ALL SELECT 'S1', 8 FROM DUAL UNION ALL SELECT 'S2', 9 FROM DUAL);
COMMIT;
