-- V14: SECTIONS master (below DEPARTMENTS) and EMPLOYEE_JOB_DETAILS.SECTION_ID. Not applied yet. Run by hand on HRMS with the
-- backend stopped (Flyway is validate-only), then record it with db/flyway_record_v14.sql. Rollback: db/rollback_V14.sql.
-- Safe on any database: dev already has SECTIONS (from db/create_sections_nilepet.sql, 244 rows), so every step that may
-- already be done is skipped instead of failing. The new column is nullable, so every existing job record stays valid.
DECLARE
  PROCEDURE run_ignoring(p_sql VARCHAR2, p_code NUMBER) IS
  BEGIN
    EXECUTE IMMEDIATE p_sql;
  EXCEPTION
    WHEN OTHERS THEN
      IF SQLCODE != p_code THEN RAISE; END IF;
  END;
BEGIN
  -- ORA-00955: name is already used by an existing object
  run_ignoring('CREATE SEQUENCE HRMS.SEQ_SECTIONS INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999 NOCYCLE NOCACHE NOORDER', -955);
  run_ignoring('CREATE TABLE HRMS.SECTIONS (
	SECTION_ID NUMBER(20,0) NOT NULL,
	DEPT_ID NUMBER(20,0) NOT NULL,
	SECTION_CODE VARCHAR2(30 CHAR) NOT NULL,
	SECTION_NAME VARCHAR2(200 CHAR) NOT NULL,
	SECTION_NAME_AR NVARCHAR2(200) NOT NULL,
	IS_ACTIVE NUMBER(1,0) DEFAULT 1 NOT NULL,
	CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
	UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
	VERSION NUMBER(10,0) DEFAULT 0 NOT NULL,
	CONSTRAINT PK_SECTIONS PRIMARY KEY (SECTION_ID),
	CONSTRAINT UQ_SECTIONS_CODE UNIQUE (SECTION_CODE),
	CONSTRAINT FK_SECTIONS_DEPT_ID FOREIGN KEY (DEPT_ID) REFERENCES HRMS.DEPARTMENTS(DEPT_ID),
	CONSTRAINT CHK_SECTIONS_ACTIVE CHECK (IS_ACTIVE IN (0,1))
  )', -955);
  run_ignoring('CREATE INDEX IDX_SECTIONS_DEPT_ID ON HRMS.SECTIONS (DEPT_ID)', -955);
  -- A table made by the dev script has BYTE columns; a 200-character accented name would overflow. Widening is harmless.
  EXECUTE IMMEDIATE 'ALTER TABLE HRMS.SECTIONS MODIFY (SECTION_CODE VARCHAR2(30 CHAR), SECTION_NAME VARCHAR2(200 CHAR))';
  -- ORA-01430: column being added already exists in table
  run_ignoring('ALTER TABLE HRMS.EMPLOYEE_JOB_DETAILS ADD (SECTION_ID NUMBER(20,0) CONSTRAINT FK_EJD_SECTION REFERENCES HRMS.SECTIONS(SECTION_ID))', -1430);
  run_ignoring('CREATE INDEX IDX_EJD_SECTION ON HRMS.EMPLOYEE_JOB_DETAILS (SECTION_ID)', -955);
END;
/
