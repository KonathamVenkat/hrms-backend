-- residence validity on identity info, work address and phone on experience. Not applied yet. Run by hand on HRMS with the
-- backend stopped (Flyway is validate-only), then record it with db/flyway_record_v17.sql. Rollback: db/rollback_V17.sql.
-- Additive and nullable: every existing row stays valid. English is VARCHAR2 with CHAR semantics, Arabic NVARCHAR2.
CREATE SEQUENCE HRMS.SEQ_SPECIALIZATIONS INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999 NOCYCLE NOCACHE NOORDER;

CREATE TABLE HRMS.SPECIALIZATIONS (
	SPECIALIZATION_ID NUMBER(20,0) NOT NULL,
	SPECIALIZATIONS_CODE VARCHAR2(30 CHAR) NOT NULL,
	SPECIALIZATIONS_NAME VARCHAR2(200 CHAR) NOT NULL,
	SPECIALIZATIONS_NAME_AR NVARCHAR2(200) NOT NULL,
	IS_ACTIVE NUMBER(1,0) DEFAULT 1 NOT NULL,
	CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
	UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
	VERSION NUMBER(10,0) DEFAULT 0 NOT NULL,
	CONSTRAINT PK_SPECIALIZATIONS PRIMARY KEY (SPECIALIZATION_ID),
	CONSTRAINT UQ_SPECIALIZATIONS_CODE UNIQUE (SPECIALIZATIONS_CODE),
	CONSTRAINT CHK_SPECIALIZATIONS_ACTIVE CHECK (IS_ACTIVE IN (0,1))
);

ALTER TABLE HRMS.EMPLOYEES ADD (
	PLACE_OF_BIRTH NVARCHAR2(200),
	NOTES          NVARCHAR2(1000)
);

ALTER TABLE HRMS.EMPLOYEE_JOB_DETAILS ADD (
	SPECIALIZATION_ID      NUMBER(20,0) CONSTRAINT FK_EJD_SPECIALIZATION REFERENCES HRMS.SPECIALIZATIONS(SPECIALIZATION_ID),
	FORM_REQUEST_NO        VARCHAR2(30 CHAR),
	APPOINTMENT_REQUEST_NO VARCHAR2(30 CHAR),
	AFE                    VARCHAR2(30 CHAR),
	COMPANY_ID_CARD_NO     VARCHAR2(30 CHAR),
	CURRENT_WORK_ADDRESS   NVARCHAR2(300),
	CURRENT_WORK_PHONE     VARCHAR2(30 CHAR)
);
CREATE INDEX IDX_EJD_SPECIALIZATION ON HRMS.EMPLOYEE_JOB_DETAILS (SPECIALIZATION_ID);

ALTER TABLE HRMS.EMPLOYEE_IDENTITY_INFO ADD (
	DOCUMENT_TYPE         NVARCHAR2(100),
	DOCUMENT_NO           VARCHAR2(100 CHAR),
	DOCUMENT_ISSUE_DATE   DATE,
	DOCUMENT_ISSUE_PLACE  NVARCHAR2(100),
	DOCUMENT_VALID_UNTIL  DATE,
	RESIDENCE_VALID_UNTIL DATE
);

ALTER TABLE HRMS.EMPLOYEE_EXPERIENCE ADD (
	WORK_ADDRESS NVARCHAR2(300),
	WORK_PHONE   VARCHAR2(30 CHAR)
);
