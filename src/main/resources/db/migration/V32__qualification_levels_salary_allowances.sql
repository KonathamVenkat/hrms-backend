-- V32: per-employee allowances on the salary record (payroll step 4a).
-- QUALIFICATION_LEVELS: the levels of the Qualification Allowance, each with its monthly amount (the March 2026 salary
-- sheet pays 135,000, 195,000, 202,500 or 270,000; db/seed_qualification_levels_mar2026.sql loads them).
-- EMPLOYEE_SALARY: the Social Allowance and the qualification level of a salary, with the amounts COPIED when the salary
-- is assigned, so a later change of a level's amount or of the Social default never rewrites a past salary.
-- Both allowances are earnings: they count in gross, so Insurance (8%) and Armed Forces (1/30) are charged on them.
-- Not applied yet. Run by hand on HRMS with the backend stopped (Flyway is validate-only), then record it with
-- db/flyway_record_v32.sql. Rollback: db/rollback_V32.sql. Additive: the new salary columns are nullable.
CREATE SEQUENCE HRMS.SEQ_QUALIFICATION_LEVELS INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999 NOCYCLE NOCACHE NOORDER;
CREATE TABLE HRMS.QUALIFICATION_LEVELS (
	QUALIFICATION_LEVEL_ID NUMBER(20,0) NOT NULL,
	QUALIFICATION_LEVELS_CODE VARCHAR2(30 CHAR) NOT NULL,
	QUALIFICATION_LEVELS_NAME VARCHAR2(200 CHAR) NOT NULL,
	QUALIFICATION_LEVELS_NAME_AR NVARCHAR2(200) NOT NULL,
	MONTHLY_AMOUNT NUMBER(12,2) NOT NULL,
	SORT_ORDER NUMBER(4,0),
	IS_ACTIVE NUMBER(1,0) DEFAULT 1 NOT NULL,
	CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
	UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
	VERSION NUMBER(10,0) DEFAULT 0 NOT NULL,
	CONSTRAINT PK_QUALIFICATION_LEVELS PRIMARY KEY (QUALIFICATION_LEVEL_ID),
	CONSTRAINT UQ_QUALIFICATION_LEVELS_CODE UNIQUE (QUALIFICATION_LEVELS_CODE),
	CONSTRAINT CHK_QUALIFICATION_LEVELS_ACTIVE CHECK (IS_ACTIVE IN (0,1)),
	CONSTRAINT CHK_QUALIFICATION_LEVELS_AMOUNT CHECK (MONTHLY_AMOUNT > 0)
);
-- Names are unique ignoring case, like the other masters (V27).
CREATE UNIQUE INDEX HRMS.UQ_QUALIFICATION_LEVELS_NAME ON HRMS.QUALIFICATION_LEVELS (UPPER(QUALIFICATION_LEVELS_NAME));
ALTER TABLE HRMS.EMPLOYEE_SALARY ADD (
	SOCIAL_AMOUNT NUMBER(12,2),
	QUALIFICATION_LEVEL_ID NUMBER(20,0) CONSTRAINT FK_ESAL_QUALIFICATION_LEVEL
		REFERENCES HRMS.QUALIFICATION_LEVELS (QUALIFICATION_LEVEL_ID),
	QUALIFICATION_AMOUNT NUMBER(12,2),
	CONSTRAINT CHK_ESAL_SOCIAL_AMOUNT CHECK (SOCIAL_AMOUNT IS NULL OR SOCIAL_AMOUNT > 0),
	-- A level and its amount go together; IS NOT NULL is spelled out because a CHECK passes on UNKNOWN.
	CONSTRAINT CHK_ESAL_QUALIFICATION CHECK ((QUALIFICATION_LEVEL_ID IS NULL AND QUALIFICATION_AMOUNT IS NULL)
		OR (QUALIFICATION_LEVEL_ID IS NOT NULL AND QUALIFICATION_AMOUNT IS NOT NULL AND QUALIFICATION_AMOUNT > 0))
);
CREATE INDEX HRMS.IDX_ESAL_QUALIFICATION_LEVEL ON HRMS.EMPLOYEE_SALARY (QUALIFICATION_LEVEL_ID);
