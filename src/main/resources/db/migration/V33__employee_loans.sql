-- V33: the loan register (payroll step 4b-1). HR_ADMIN records an approved loan or advance of an employee: its type
-- (a salary component flagged IS_LOAN), principal, number of monthly instalments and first month. The instalment is
-- principal / months, as in the salary sheet (=12122140/36). For a loan already running when it is entered,
-- INSTALMENTS_PAID says how many instalments were deducted before; the monthly payroll run (step 5) adds to it.
-- One ACTIVE loan per employee and type (the sheet records a second one under the "... 2" types); closed and
-- cancelled loans stay as history.
-- SALARY_COMPONENTS.IS_LOAN marks the components that are loan types; db/loan_types_mar2026.sql sets it on the 17
-- advance components of the sheet. Not applied yet. Run by hand on HRMS with the backend stopped (Flyway is
-- validate-only), then record it with db/flyway_record_v33.sql. Rollback: db/rollback_V33.sql. Additive.
ALTER TABLE HRMS.SALARY_COMPONENTS ADD (
	IS_LOAN NUMBER(1,0) DEFAULT 0 NOT NULL,
	CONSTRAINT CHK_COMP_IS_LOAN CHECK (IS_LOAN IN (0,1))
);
CREATE SEQUENCE HRMS.SEQ_EMPLOYEE_LOANS INCREMENT BY 1 MINVALUE 1 MAXVALUE 9999999999 NOCYCLE NOCACHE NOORDER;
CREATE TABLE HRMS.EMPLOYEE_LOANS (
	LOAN_ID NUMBER(20,0) NOT NULL,
	EMPLOYEE_ID NUMBER(20,0) NOT NULL,
	COMPONENT_ID NUMBER(10,0) NOT NULL,
	PRINCIPAL NUMBER(14,2) NOT NULL,
	INSTALMENT_COUNT NUMBER(3,0) NOT NULL,
	MONTHLY_INSTALMENT NUMBER(12,2) NOT NULL,
	START_MONTH DATE NOT NULL,
	INSTALMENTS_PAID NUMBER(3,0) DEFAULT 0 NOT NULL,
	STATUS VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
	STATUS_REASON VARCHAR2(500 CHAR),
	STATUS_CHANGED_BY VARCHAR2(100 CHAR),
	STATUS_CHANGED_AT TIMESTAMP,
	REMARKS VARCHAR2(500 CHAR),
	CREATED_BY VARCHAR2(100 CHAR),
	CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
	UPDATED_BY VARCHAR2(100 CHAR),
	UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
	VERSION NUMBER(10,0) DEFAULT 0 NOT NULL,
	CONSTRAINT PK_EMPLOYEE_LOANS PRIMARY KEY (LOAN_ID),
	CONSTRAINT FK_ELOAN_EMPLOYEE FOREIGN KEY (EMPLOYEE_ID) REFERENCES HRMS.EMPLOYEES (EMPLOYEE_ID),
	CONSTRAINT FK_ELOAN_COMPONENT FOREIGN KEY (COMPONENT_ID) REFERENCES HRMS.SALARY_COMPONENTS (COMPONENT_ID),
	CONSTRAINT CHK_ELOAN_PRINCIPAL CHECK (PRINCIPAL > 0),
	CONSTRAINT CHK_ELOAN_COUNT CHECK (INSTALMENT_COUNT BETWEEN 1 AND 360),
	CONSTRAINT CHK_ELOAN_INSTALMENT CHECK (MONTHLY_INSTALMENT > 0),
	CONSTRAINT CHK_ELOAN_PAID CHECK (INSTALMENTS_PAID BETWEEN 0 AND INSTALMENT_COUNT),
	-- The first day of a month: the loan is deducted by month, never from a day.
	CONSTRAINT CHK_ELOAN_START CHECK (START_MONTH = TRUNC(START_MONTH, 'MM')),
	CONSTRAINT CHK_ELOAN_STATUS CHECK (STATUS IN ('ACTIVE','CLOSED','CANCELLED'))
);
-- One ACTIVE loan per employee and type; rows where both expressions are NULL (closed, cancelled) are left out.
CREATE UNIQUE INDEX HRMS.UQ_ELOAN_ONE_ACTIVE ON HRMS.EMPLOYEE_LOANS (
	CASE WHEN STATUS = 'ACTIVE' THEN EMPLOYEE_ID END,
	CASE WHEN STATUS = 'ACTIVE' THEN COMPONENT_ID END);
CREATE INDEX HRMS.IDX_ELOAN_EMPLOYEE ON HRMS.EMPLOYEE_LOANS (EMPLOYEE_ID, STATUS);
CREATE INDEX HRMS.IDX_ELOAN_COMPONENT ON HRMS.EMPLOYEE_LOANS (COMPONENT_ID);
CREATE INDEX HRMS.IDX_ELOAN_STATUS ON HRMS.EMPLOYEE_LOANS (STATUS, START_MONTH);
