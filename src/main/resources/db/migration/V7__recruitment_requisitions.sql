-- V7: recruitment, phase R1 -- setup masters, job requisitions and their approval record.
-- Not applied yet. Run by hand on HRMS (Flyway is validate-only), then record it with db/flyway_record_v7.sql.
-- Rollback: db/rollback_V7.sql.
-- Later phases add their own tables (postings and candidates V8, interviews V9, offers and onboarding V10).
-- Conventions: IDs come from the sequences (no triggers), flags are NUMBER(1) with CHECK, VARCHAR2 uses CHAR semantics,
-- money is NUMBER(14,3), bilingual names are *_NAME + *_NAME_AR (NVARCHAR2), every table has VERSION.
-- Business rules that need the code (approver is not the requester, state machine) live in the service layer;
-- the CHECK constraints below are the last line of defence.

-- ===== 1. Sequences =====
CREATE SEQUENCE HRMS.SEQ_REC_STAGES            INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999 NOCYCLE NOCACHE NOORDER;
CREATE SEQUENCE HRMS.SEQ_REC_REJECT_REASONS    INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999 NOCYCLE NOCACHE NOORDER;
CREATE SEQUENCE HRMS.SEQ_JOB_REQUISITIONS      INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999 NOCYCLE NOCACHE NOORDER;
CREATE SEQUENCE HRMS.SEQ_REQUISITION_APPROVALS INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999 NOCYCLE NOCACHE NOORDER;
-- Feeds the year-prefixed business code REQ-YYYY-NNNNNN, formatted in Java.
CREATE SEQUENCE HRMS.SEQ_REC_REQ_CODE          INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999 NOCYCLE NOCACHE NOORDER;

-- ===== 2. Setup masters (SYSTEM_ADMIN maintains them) =====
-- Pipeline stages. Code branches on STAGE_TYPE, never on the name. IS_SYSTEM rows cannot be deleted or re-typed.
CREATE TABLE HRMS.RECRUITMENT_STAGES (
    STAGE_ID       NUMBER(20,0) NOT NULL,
    STAGE_CODE     VARCHAR2(30 CHAR) NOT NULL,
    STAGE_NAME     VARCHAR2(100 CHAR) NOT NULL,
    STAGE_NAME_AR  NVARCHAR2(200) NOT NULL,
    STAGE_TYPE     VARCHAR2(20 CHAR) DEFAULT 'OPEN' NOT NULL,
    SORT_ORDER     NUMBER(3,0) DEFAULT 0 NOT NULL,
    IS_SYSTEM      NUMBER(1,0) DEFAULT 0 NOT NULL,
    IS_ACTIVE      NUMBER(1,0) DEFAULT 1 NOT NULL,
    CREATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    VERSION        NUMBER(10,0) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_REC_STAGES        PRIMARY KEY (STAGE_ID),
    CONSTRAINT UQ_REC_STAGE_CODE    UNIQUE (STAGE_CODE),
    CONSTRAINT CHK_REC_STAGE_CODE   CHECK (REGEXP_LIKE(STAGE_CODE, '^[A-Z0-9_]+$')),
    CONSTRAINT CHK_REC_STAGE_TYPE   CHECK (STAGE_TYPE IN ('OPEN','HIRED','REJECTED','WITHDRAWN')),
    CONSTRAINT CHK_REC_STAGE_SYSTEM CHECK (IS_SYSTEM IN (0,1)),
    CONSTRAINT CHK_REC_STAGE_ACTIVE CHECK (IS_ACTIVE IN (0,1))
);
-- At most one active stage per terminal type, so "the" HIRED / REJECTED / WITHDRAWN stage is unambiguous.
CREATE UNIQUE INDEX UQ_REC_STAGE_TERMINAL ON HRMS.RECRUITMENT_STAGES (
    CASE WHEN STAGE_TYPE <> 'OPEN' AND IS_ACTIVE = 1 THEN STAGE_TYPE END);

CREATE TABLE HRMS.REJECTION_REASONS (
    REASON_ID      NUMBER(20,0) NOT NULL,
    REASON_CODE    VARCHAR2(30 CHAR) NOT NULL,
    REASON_NAME    VARCHAR2(150 CHAR) NOT NULL,
    REASON_NAME_AR NVARCHAR2(300) NOT NULL,
    APPLIES_TO     VARCHAR2(20 CHAR) DEFAULT 'APPLICATION' NOT NULL,
    SORT_ORDER     NUMBER(3,0) DEFAULT 0 NOT NULL,
    IS_ACTIVE      NUMBER(1,0) DEFAULT 1 NOT NULL,
    CREATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    VERSION        NUMBER(10,0) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_REJECTION_REASONS PRIMARY KEY (REASON_ID),
    CONSTRAINT UQ_REJ_REASON_CODE   UNIQUE (REASON_CODE),
    CONSTRAINT CHK_REJ_REASON_CODE  CHECK (REGEXP_LIKE(REASON_CODE, '^[A-Z0-9_]+$')),
    CONSTRAINT CHK_REJ_APPLIES      CHECK (APPLIES_TO IN ('APPLICATION','OFFER')),
    CONSTRAINT CHK_REJ_ACTIVE       CHECK (IS_ACTIVE IN (0,1))
);

-- ===== 3. Job requisition =====
-- A department head's request to fill one or more positions. REQUESTED_BY is the head (or HR on their behalf).
CREATE TABLE HRMS.JOB_REQUISITIONS (
    REQUISITION_ID        NUMBER(20,0) NOT NULL,
    REQUISITION_CODE      VARCHAR2(30 CHAR) NOT NULL,
    JOB_TITLE             VARCHAR2(200 CHAR) NOT NULL,
    JOB_TITLE_AR          NVARCHAR2(300),
    DEPARTMENT_ID         NUMBER(20,0) NOT NULL,
    DESIGNATION_ID        NUMBER(20,0) NOT NULL,
    LOCATION_ID           NUMBER(10,0),
    REPORTING_MANAGER_ID  NUMBER(20,0),
    REQUESTED_BY          NUMBER(20,0) NOT NULL,
    NO_OF_POSITIONS       NUMBER(4,0) DEFAULT 1 NOT NULL,
    FILLED_POSITIONS      NUMBER(4,0) DEFAULT 0 NOT NULL,
    EMPLOYMENT_TYPE       VARCHAR2(30 CHAR) NOT NULL,
    REQUISITION_TYPE      VARCHAR2(20 CHAR) DEFAULT 'NEW' NOT NULL,
    REPLACED_EMPLOYEE_ID  NUMBER(20,0),
    MIN_EXPERIENCE_YEARS  NUMBER(4,1) DEFAULT 0 NOT NULL,
    MAX_EXPERIENCE_YEARS  NUMBER(4,1),
    MIN_SALARY            NUMBER(14,3),
    MAX_SALARY            NUMBER(14,3),
    CURRENCY              VARCHAR2(5 CHAR) NOT NULL,
    PRIORITY              VARCHAR2(10 CHAR) DEFAULT 'MEDIUM' NOT NULL,
    TARGET_JOIN_DATE      DATE,
    JUSTIFICATION         VARCHAR2(1000 CHAR),
    STATUS                VARCHAR2(20 CHAR) DEFAULT 'DRAFT' NOT NULL,
    CLOSED_AT             TIMESTAMP,
    CREATED_BY            VARCHAR2(36),
    CREATED_AT            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_BY            VARCHAR2(36),
    UPDATED_AT            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    VERSION               NUMBER(10,0) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_JOB_REQUISITIONS  PRIMARY KEY (REQUISITION_ID),
    CONSTRAINT UQ_JOB_REQ_CODE      UNIQUE (REQUISITION_CODE),
    CONSTRAINT CHK_REQ_POSITIONS    CHECK (NO_OF_POSITIONS > 0 AND FILLED_POSITIONS >= 0 AND FILLED_POSITIONS <= NO_OF_POSITIONS),
    CONSTRAINT CHK_REQ_EMP_TYPE     CHECK (EMPLOYMENT_TYPE IN ('FULL_TIME','PART_TIME','CONTRACT','INTERN','CONSULTANT')),
    CONSTRAINT CHK_REQ_TYPE         CHECK (REQUISITION_TYPE IN ('NEW','REPLACEMENT')),
    CONSTRAINT CHK_REQ_REPLACEMENT  CHECK (REQUISITION_TYPE <> 'REPLACEMENT' OR REPLACED_EMPLOYEE_ID IS NOT NULL),
    CONSTRAINT CHK_REQ_PRIORITY     CHECK (PRIORITY IN ('LOW','MEDIUM','HIGH','URGENT')),
    CONSTRAINT CHK_REQ_STATUS       CHECK (STATUS IN ('DRAFT','PENDING_APPROVAL','APPROVED','REJECTED','ON_HOLD','FILLED','CLOSED','CANCELLED')),
    CONSTRAINT CHK_REQ_EXPERIENCE   CHECK (MIN_EXPERIENCE_YEARS >= 0 AND (MAX_EXPERIENCE_YEARS IS NULL OR MAX_EXPERIENCE_YEARS >= MIN_EXPERIENCE_YEARS)),
    CONSTRAINT CHK_REQ_SALARY       CHECK ((MIN_SALARY IS NULL OR MIN_SALARY >= 0) AND (MAX_SALARY IS NULL OR MIN_SALARY IS NULL OR MAX_SALARY >= MIN_SALARY)),
    CONSTRAINT FK_REQ_DEPARTMENT    FOREIGN KEY (DEPARTMENT_ID)        REFERENCES HRMS.DEPARTMENTS(DEPT_ID),
    CONSTRAINT FK_REQ_DESIGNATION   FOREIGN KEY (DESIGNATION_ID)       REFERENCES HRMS.DESIGNATIONS(DESIG_ID),
    CONSTRAINT FK_REQ_LOCATION      FOREIGN KEY (LOCATION_ID)          REFERENCES HRMS.OFFICE_LOCATIONS(LOCATION_ID),
    CONSTRAINT FK_REQ_MANAGER       FOREIGN KEY (REPORTING_MANAGER_ID) REFERENCES HRMS.EMPLOYEES(EMPLOYEE_ID),
    CONSTRAINT FK_REQ_REQUESTED_BY  FOREIGN KEY (REQUESTED_BY)         REFERENCES HRMS.EMPLOYEES(EMPLOYEE_ID),
    CONSTRAINT FK_REQ_REPLACED_EMP  FOREIGN KEY (REPLACED_EMPLOYEE_ID) REFERENCES HRMS.EMPLOYEES(EMPLOYEE_ID)
);
-- Serves: list by status/department/requester (screen filters) and the FK lookups.
CREATE INDEX IDX_REQ_STATUS      ON HRMS.JOB_REQUISITIONS (STATUS, CREATED_AT);
CREATE INDEX IDX_REQ_DEPT        ON HRMS.JOB_REQUISITIONS (DEPARTMENT_ID, STATUS);
CREATE INDEX IDX_REQ_REQUESTER   ON HRMS.JOB_REQUISITIONS (REQUESTED_BY);
CREATE INDEX IDX_REQ_DESIGNATION ON HRMS.JOB_REQUISITIONS (DESIGNATION_ID);
CREATE INDEX IDX_REQ_LOCATION    ON HRMS.JOB_REQUISITIONS (LOCATION_ID);
CREATE INDEX IDX_REQ_MANAGER     ON HRMS.JOB_REQUISITIONS (REPORTING_MANAGER_ID);
CREATE INDEX IDX_REQ_REPLACED    ON HRMS.JOB_REQUISITIONS (REPLACED_EMPLOYEE_ID);

-- ===== 4. Approval record =====
-- One row per decision (a pending requisition simply has none). LEVEL_NO is 1 today; a second level
-- (finance, management) can be added later without a schema change.
-- Approving requires both confirmations: the budget was checked with Finance and Management agreed outside the system.
CREATE TABLE HRMS.REQUISITION_APPROVALS (
    APPROVAL_ID          NUMBER(20,0) NOT NULL,
    REQUISITION_ID       NUMBER(20,0) NOT NULL,
    LEVEL_NO             NUMBER(2,0) DEFAULT 1 NOT NULL,
    APPROVER_ID          NUMBER(20,0) NOT NULL,
    STATUS               VARCHAR2(20 CHAR) NOT NULL,
    BUDGET_CONFIRMED     NUMBER(1,0) DEFAULT 0 NOT NULL,
    MANAGEMENT_CONFIRMED NUMBER(1,0) DEFAULT 0 NOT NULL,
    COMMENTS             VARCHAR2(500 CHAR),
    ACTION_AT            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_AT           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_REQ_APPROVALS     PRIMARY KEY (APPROVAL_ID),
    CONSTRAINT UQ_REQ_APPR_LEVEL    UNIQUE (REQUISITION_ID, LEVEL_NO),
    CONSTRAINT CHK_RAPPR_STATUS     CHECK (STATUS IN ('APPROVED','REJECTED')),
    CONSTRAINT CHK_RAPPR_FLAGS      CHECK (BUDGET_CONFIRMED IN (0,1) AND MANAGEMENT_CONFIRMED IN (0,1)),
    CONSTRAINT CHK_RAPPR_APPROVED   CHECK (STATUS <> 'APPROVED' OR (BUDGET_CONFIRMED = 1 AND MANAGEMENT_CONFIRMED = 1)),
    CONSTRAINT CHK_RAPPR_REJECTED   CHECK (STATUS <> 'REJECTED' OR COMMENTS IS NOT NULL),
    CONSTRAINT FK_RAPPR_REQ         FOREIGN KEY (REQUISITION_ID) REFERENCES HRMS.JOB_REQUISITIONS(REQUISITION_ID),
    CONSTRAINT FK_RAPPR_APPROVER    FOREIGN KEY (APPROVER_ID)    REFERENCES HRMS.EMPLOYEES(EMPLOYEE_ID)
);
CREATE INDEX IDX_RAPPR_APPROVER ON HRMS.REQUISITION_APPROVALS (APPROVER_ID);

